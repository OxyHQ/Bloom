#!/usr/bin/env node
/**
 * One spec, three outputs. `spec/language.json` is the Bloom language as data;
 * this script writes, from it:
 *
 * - `src/generated/spec.generated.ts`: the runtime's tables (scales, colour
 *   roles, layering, environment, modifier and node rules);
 * - `src/generated/web-sheet.generated.ts`: the web stylesheet, one atomic class
 *   per property and token value, and the table the runtime picks classes from;
 * - `../bloom-language-compiler/crates/compiler/src/spec.generated.rs`: the
 *   compiler's tables (every name it checks a chain against);
 * - `src/generated/sf-symbols.generated.ts`: each mapped Bloom icon's SF Symbol,
 *   by the icon component itself, for iOS's own components (imported only by
 *   `*.ios.tsx` files, so the icons it names reach no other platform's bundle).
 *
 * `--check` writes nothing and fails when a committed output differs, so CI
 * catches a spec edit whose outputs were not regenerated.
 *
 * The web declarations come from react-native-web's own style compiler, so a
 * class says exactly what react-native-web would have written inline for the
 * same style; only the logical edges (`paddingStart`…) are written as CSS
 * logical properties, which react-native-web leaves to per-render localisation.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, '..');
const compilerRoot = join(packageRoot, '../bloom-language-compiler');
const require = createRequire(join(packageRoot, '../../package.json'));
const { atomic } = require('react-native-web/dist/cjs/exports/StyleSheet/compiler');
const { preprocess } = require('react-native-web/dist/cjs/exports/StyleSheet/preprocess');

const spec = JSON.parse(readFileSync(join(packageRoot, 'spec/language.json'), 'utf8'));
const check = process.argv.includes('--check');

const withoutComment = (table) =>
  Object.fromEntries(Object.entries(table).filter(([key]) => key !== '$comment'));

const { scales, enums } = spec;
const typeRamp = withoutComment(spec.typeRamp);
const colors = withoutComment(spec.colors);
const modifiers = withoutComment(spec.modifiers);
const nodes = withoutComment(spec.nodes);
const glass = withoutComment(spec.glass);
const sfSymbols = withoutComment(spec.sfSymbols);

/** A role's web value: its canonical CSS variable, or, for a colour the same in every theme, the colour. */
const webColor = (css) => (css.startsWith('#') ? css : `var(--${css})`);

const typeFamilies = [];
for (const variant of Object.keys(typeRamp)) {
  const family = variant.replace(/-(regular|medium|semibold|bold)$/, '');
  if (!typeFamilies.includes(family)) typeFamilies.push(family);
}

const HEADER =
  'GENERATED by packages/bloom-language/scripts/generate.mjs from spec/language.json. Do not edit.';

// ── The runtime's tables ─────────────────────────────────────────

function ts(value) {
  return JSON.stringify(value, null, 2);
}

const layerRank = {};
spec.layers.forEach((kinds, rank) => {
  for (const kind of kinds) layerRank[kind] = rank;
});

const nodeModifiers = {};
const constructors = {};
for (const [kind, node] of Object.entries(nodes)) {
  nodeModifiers[kind] =
    node.universal === false ? [...node.modifiers] : [...spec.universal, ...node.modifiers];
  for (const name of node.constructors) constructors[name] = kind;
}

const runtime = `// ${HEADER}
/* eslint-disable */

export const SPACE = ${ts(scales.space)} as const;
export const CORNER = ${ts(scales.corner)} as const;
export const FONT_SIZE = ${ts(scales.fontSize)} as const;
export const LEADING = ${ts(scales.leading)} as const;
export const TRACKING = ${ts(scales.tracking)} as const;
export const WEIGHT = ${ts(scales.weight)} as const;
export const ICON_SIZE = ${ts(scales.iconSize)} as const;
export const AVATAR_SIZE = ${ts(scales.avatarSize)} as const;
export const OPACITY = ${ts(scales.opacity)} as const;
export const BORDER_WIDTH = ${ts(scales.borderWidth)} as const;
export const HIT_SLOP = ${ts(scales.hitSlop)} as const;
export const SHRINK = ${ts(scales.shrink)} as const;
export const ALIGNMENT = ${ts(scales.alignment)} as const;
export const GLASS_OPACITY = ${ts(scales.glassOpacity)} as const;
export const DURATION = ${ts(scales.duration)} as const;

/** Bloom's type ramp: \`<family>-<weight>\` → [fontSize, lineHeight, letterSpacing, fontWeight]. */
export const TYPE_FAMILIES = ${ts(typeFamilies)} as const;
export const TYPE_RAMP = ${ts(typeRamp)} as const;

/** Colour roles: the theme colour each paints with on native, and its web value (its CSS variable, or a fixed colour). */
export const COLORS = ${ts(
  Object.fromEntries(
    Object.entries(colors).map(([role, [paint, css]]) => [role, { paint, web: webColor(css) }]),
  ),
)} as const;

export const ENUMS = ${ts(enums)} as const;

/** Each glass material, as each platform draws it. */
export const GLASS = ${ts(glass)} as const;

/** The colour role a solid control of each Bloom tone fills with. */
export const TONE_ROLE = ${ts(withoutComment(spec.toneRole))} as const;

/** A box modifier's place in one view's stack of effects (see style.ts, layers). */
export const LAYER_RANK = ${ts(layerRank)} as const;

/** The traits a view hands everything inside it. */
export const ENVIRONMENT = ${ts(spec.environment.traits)} as const;
export const ENVIRONMENT_DEFAULTS = ${ts(spec.environment.defaults)} as const;

/** Each modifier's parameter types, in order. */
export const MODIFIERS = ${ts(modifiers)} as const;

/** The modifiers each node kind takes. */
export const NODE_MODIFIERS = ${ts(nodeModifiers)} as const;

/** The constructor functions, by the node kind they make. */
export const CONSTRUCTORS = ${ts(constructors)} as const;
`;

// ── The web stylesheet ───────────────────────────────────────────

/** FNV-1a, base 36: a short class name that is stable across builds. */
function hash(text) {
  let value = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    value ^= text.charCodeAt(i);
    value = Math.imul(value, 0x01000193) >>> 0;
  }
  return value.toString(36);
}

/**
 * The logical edges, as CSS logical properties. react-native-web localises
 * them per render (inline) or per StyleSheet; a class cannot, so the browser
 * resolves them against the document's direction (Bloom sets it on the root).
 */
const LOGICAL = {
  paddingStart: 'padding-inline-start',
  paddingEnd: 'padding-inline-end',
  marginStart: 'margin-inline-start',
  marginEnd: 'margin-inline-end',
  borderStartWidth: 'border-inline-start-width',
  borderEndWidth: 'border-inline-end-width',
  borderStartColor: 'border-inline-start-color',
  borderEndColor: 'border-inline-end-color',
};
/** react-native-web's precedence group for logical longhands. */
const LOGICAL_ORDER = 2.2;

/** The web value of a role. */
const roleValue = (role) => webColor(colors[role][1]);

const rules = [];
const classes = {};

/** One class for one property at one value. `key` is what the runtime looks the class up by. */
function addClass(property, value, key) {
  if (classes[key]) return;
  const name = `bl${hash(key)}`;
  let declarations;
  let order;
  if (LOGICAL[property]) {
    const css = typeof value === 'number' ? `${value}px` : value;
    declarations = `${LOGICAL[property]}:${css};`;
    order = LOGICAL_ORDER;
  } else {
    const [, ordered] = atomic(preprocess({ [property]: value }, {}));
    if (ordered.length !== 1)
      throw new Error(`${property}: expected one rule, got ${ordered.length}`);
    const [[ruleTexts, ruleOrder]] = ordered;
    declarations = ruleTexts[0].slice(ruleTexts[0].indexOf('{') + 1, -1);
    order = ruleOrder;
  }
  rules.push({ order, name, text: `.${name}{${declarations}}` });
  classes[key] = name;
}

const numbers = (table) => [...new Set(Object.values(table).filter((v) => typeof v === 'number'))];
const spaceValues = numbers(scales.space);
const fontSizes = [
  ...new Set([...numbers(scales.fontSize), ...Object.values(typeRamp).map((s) => s[0])]),
];

const valueClass = (property, value) => addClass(property, value, `${property}:${value}`);
const roleClass = (property, role) => addClass(property, roleValue(role), `${property}:@${role}`);

// Box: padding, negative padding (margins), frame and stack spacing.
for (const edge of ['Top', 'Bottom', 'Start', 'End']) {
  for (const value of spaceValues) valueClass(`padding${edge}`, value);
  for (const value of spaceValues) if (value > 0) valueClass(`margin${edge}`, -value);
}
for (const property of [
  'width',
  'height',
  'minWidth',
  'minHeight',
  'maxWidth',
  'maxHeight',
  'gap',
]) {
  for (const value of spaceValues) valueClass(property, value);
}
for (const value of numbers(scales.corner)) valueClass('borderRadius', value);
valueClass('overflow', 'hidden');
for (const value of numbers(scales.opacity)) valueClass('opacity', value);
// Borders: react-native-web's hairline is 1px.
for (const edge of ['', 'Top', 'Bottom', 'Start', 'End']) {
  valueClass(`border${edge}Width`, 1);
  for (const role of Object.keys(colors)) roleClass(`border${edge}Color`, role);
}
for (const role of Object.keys(colors)) {
  roleClass('color', role);
  roleClass('backgroundColor', role);
}
// Stacks and placement.
valueClass('flexDirection', 'row');
valueClass('position', 'relative');
valueClass('position', 'absolute');
for (const side of ['top', 'right', 'bottom', 'left']) valueClass(side, 0);
valueClass('justifyContent', 'space-between');
for (const value of Object.values(scales.alignment)) valueClass('alignItems', value);
valueClass('flex', 1);
for (const value of numbers(scales.shrink)) valueClass('flexShrink', value);
// Type: sizes, ramp line heights, every size at every leading and every tracking, weights.
for (const value of fontSizes) valueClass('fontSize', value);
const lineHeights = new Set(Object.values(typeRamp).map((s) => s[1]));
for (const size of fontSizes)
  for (const ratio of Object.values(scales.leading)) lineHeights.add(size * ratio);
for (const value of lineHeights) valueClass('lineHeight', value);
const letterSpacings = new Set(Object.values(typeRamp).map((s) => s[2]));
for (const size of fontSizes)
  for (const em of Object.values(scales.tracking)) letterSpacings.add(size * em);
for (const value of letterSpacings) valueClass('letterSpacing', value);
for (const value of new Set([
  ...Object.values(scales.weight),
  ...Object.values(typeRamp).map((s) => s[3]),
])) {
  valueClass('fontWeight', value);
}
valueClass('whiteSpace', 'nowrap');
// Text: slant, decoration and case (style.ts, textStyle). Alignment stays inline:
// react-native-web writes it per direction, which one class cannot.
valueClass('fontStyle', 'italic');
for (const value of ['underline', 'line-through', 'underline line-through'])
  valueClass('textDecorationLine', value);
for (const value of enums.textCase) valueClass('textTransform', value);

// react-native-web's precedence (shorthands before longhands), then by name, so
// the sheet is the same text on every run.
rules.sort((a, b) => a.order - b.order || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

const webSheet = `// ${HEADER}
/* eslint-disable */

/**
 * Every class the language can put on a react-native-web host, in
 * react-native-web's precedence order. Adopted once on the web (web-sheet.ts).
 */
export const WEB_SHEET = ${JSON.stringify(rules.map((rule) => rule.text).join('\n'))};

/** \`property:value\` (a role as \`property:@role\`) → the class that sets it. */
export const WEB_CLASS: Readonly<Record<string, string>> = ${ts(classes)};
`;

// ── The compiler's tables ────────────────────────────────────────

const negative = Object.keys(scales.space).map((name) => `-${name}`);
const tokenSets = {
  space: Object.keys(scales.space),
  padding: [...Object.keys(scales.space), ...negative],
  spacing: [...Object.keys(scales.space), ...enums.spacingExtra],
  corner: [...Object.keys(scales.corner), ...enums.cornerExtra],
  font: [...typeFamilies, ...Object.keys(scales.fontSize), ...enums.fontFamily],
  weight: Object.keys(scales.weight),
  leading: Object.keys(scales.leading),
  tracking: Object.keys(scales.tracking),
  color: Object.keys(colors),
  borderWidth: Object.keys(scales.borderWidth),
  opacity: Object.keys(scales.opacity),
  hitSlop: Object.keys(scales.hitSlop),
  shrink: Object.keys(scales.shrink),
  alignment: Object.keys(scales.alignment),
  iconSize: Object.keys(scales.iconSize),
  avatarSize: Object.keys(scales.avatarSize),
  glassOpacity: Object.keys(scales.glassOpacity),
  duration: Object.keys(scales.duration),
  ...enums,
};

const rustStr = (s) => JSON.stringify(s);
const rustList = (items) => `&[${items.map(rustStr).join(', ')}]`;
const rustOption = (s) => (s ? `Some(${rustStr(s)})` : 'None');

const rust = `//! ${HEADER}
//!
//! The names the compiler checks a chain against. Values are the runtime's;
//! the compiler never resolves a token, it only proves one is valid.

/// A node kind: the constructors that make it, every modifier it takes, and the
/// token sets its \`size()\`, \`tint()\`, \`style()\` and \`shape()\` read.
pub struct NodeSpec {
    pub kind: &'static str,
    pub constructors: &'static [&'static str],
    pub modifiers: &'static [&'static str],
    pub size: Option<&'static str>,
    pub tint: Option<&'static str>,
    pub style: Option<&'static str>,
    pub shape: Option<&'static str>,
}

/// Token set name → its token names.
pub const TOKEN_SETS: &[(&str, &[&str])] = &[
${Object.entries(tokenSets)
  .map(([name, tokens]) => `    (${rustStr(name)}, ${rustList(tokens)}),`)
  .join('\n')}
];

/// Modifier → its parameter types, in order (\`?\` optional).
pub const MODIFIERS: &[(&str, &[&str])] = &[
${Object.entries(modifiers)
  .map(([name, params]) => `    (${rustStr(name)}, ${rustList(params)}),`)
  .join('\n')}
];

pub const NODES: &[NodeSpec] = &[
${Object.entries(nodes)
  .map(
    ([kind, node]) =>
      `    NodeSpec { kind: ${rustStr(kind)}, constructors: ${rustList(node.constructors)}, modifiers: ${rustList(nodeModifiers[kind])}, size: ${rustOption(node.size)}, tint: ${rustOption(node.tint)}, style: ${rustOption(node.style)}, shape: ${rustOption(node.shape)} },`,
  )
  .join('\n')}
];

/// The keys \`frame({ … })\` takes; each value is a space token.
pub const FRAME_KEYS: &[&str] = &["width", "height", "minWidth", "minHeight", "maxWidth", "maxHeight"];
`;

// ── The SF Symbols table ─────────────────────────────────────────

// Both sides of every entry are checked: the icon is one of Bloom's, and the
// symbol is one SF Symbols names (sf-symbols-typescript, expo-router's own
// list of them).
const iconsRoot = join(packageRoot, '../../src/icons/remix');
const symbolNames = new Set(
  readFileSync(require.resolve('sf-symbols-typescript/dist/index.d.ts'), 'utf8').match(
    /(?<=\| ')[^']+(?=')/g,
  ),
);
for (const [icon, symbol] of Object.entries(sfSymbols)) {
  if (!existsSync(join(iconsRoot, `${icon}.tsx`)))
    throw new Error(`sfSymbols: ${icon} is not a Bloom icon`);
  if (!symbolNames.has(symbol))
    throw new Error(`sfSymbols: ${icon} → ${symbol} is not an SF Symbol`);
}
const sfIcons = Object.keys(sfSymbols);
const sfTable = `// ${HEADER}
/* eslint-disable */
${sfIcons.map((icon) => `import { ${icon} } from '@oxy.so/bloom/icons/${icon}';`).join('\n')}

import type { IconComponent } from '../node';

/**
 * Each mapped Bloom icon's SF Symbol, by the icon component: what the tab
 * bar, the navigation bar and system menus draw for it on iOS. Import it only
 * from \`*.ios.tsx\` files.
 */
export const SF_SYMBOLS: ReadonlyMap<IconComponent, string> = new Map<IconComponent, string>([
${sfIcons.map((icon) => `  [${icon} as IconComponent, ${JSON.stringify(sfSymbols[icon])}],`).join('\n')}
]);
`;

// ── Write or check ───────────────────────────────────────────────

const outputs = [
  [join(packageRoot, 'src/generated/spec.generated.ts'), runtime],
  [join(packageRoot, 'src/generated/web-sheet.generated.ts'), webSheet],
  [join(compilerRoot, 'crates/compiler/src/spec.generated.rs'), rust],
  [join(packageRoot, 'src/generated/sf-symbols.generated.ts'), sfTable],
];

let stale = 0;
for (const [path, text] of outputs) {
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {}
    if (current !== text) {
      console.error(`stale: ${path} (run: bun run generate in packages/bloom-language)`);
      stale += 1;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}
if (stale > 0) process.exit(1);
console.log(
  check
    ? 'language spec outputs are current'
    : `wrote ${outputs.length} outputs (${rules.length} web classes)`,
);
