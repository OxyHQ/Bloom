#!/usr/bin/env node
/**
 * The language's entries, from the files that define them. The root
 * (`src/index.ts`) is the language: its views, modifiers, values and
 * renderer. Each family of nodes is an entry of its own,
 * `@oxy.so/bloom-language/<family>`, one file in `src/entries/` re-exporting
 * the family's module in `src/controls/`; `/router` is the router. A family's
 * module declares its renderers where it defines its nodes
 * (`defineControls`), so an app's bundle carries the families it imports and
 * no other.
 *
 * This script writes, from `src/index.ts`, `src/router/index.ts` and
 * `src/entries/*.ts`:
 *
 * - `package.json#exports`: one subpath per entry;
 * - `spec/entries.generated.json`: each entry's value exports, the table the
 *   codemod writes imports from and the reference names a node's entry from;
 * - `../bloom-language-compiler/crates/compiler/src/entries.generated.rs`: the
 *   modules the compiler reads language views from (the root and each family);
 * - `src/__tests__/support/language.generated.ts`: every entry as one module,
 *   for the suites that draw every family (`import * as L`).
 *
 * An entry is a barrel: `export { … } from '…'` and `export type { … } from
 * '…'` statements only, so its names are read from its text. A name exported
 * by two entries fails the script.
 *
 * `--check` writes nothing and fails when a committed output differs.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const compilerSource = join(packageRoot, '../bloom-language-compiler/crates/compiler/src');
const check = process.argv.includes('--check');
const MODULE = '@oxy.so/bloom-language';

/** The value names a barrel exports (its `export type` names are left out). */
function valueExports(file) {
  const text = readFileSync(join(packageRoot, 'src', file), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');
  const names = [];
  let rest = text;
  for (const match of text.matchAll(/export\s+(type\s+)?\{([^}]*)\}\s*from\s*'[^']+';/g)) {
    rest = rest.replace(match[0], '');
    if (match[1]) continue;
    for (const specifier of match[2].split(',')) {
      const name = specifier.trim();
      if (!name || name.startsWith('type ')) continue;
      names.push(name.split(/\s+as\s+/).pop());
    }
  }
  if (rest.trim())
    throw new Error(`src/${file}: an entry holds only re-exports, found:\n${rest.trim()}`);
  return names.sort();
}

const families = readdirSync(join(packageRoot, 'src/entries'))
  .filter((file) => file.endsWith('.ts'))
  .map((file) => file.slice(0, -'.ts'.length))
  .sort();
if (families.includes('router')) throw new Error('src/entries/router.ts: `/router` is the router');

/** Subpath (`.` for the root) → its source file under `src/`. */
const entries = [
  ['.', 'index.ts'],
  ['router', 'router/index.ts'],
  ...families.map((family) => [family, `entries/${family}.ts`]),
];

const table = {};
const owner = new Map();
for (const [entry, file] of entries) {
  table[entry] = valueExports(file);
  for (const name of table[entry]) {
    if (owner.has(name))
      throw new Error(`${name} is exported by both ${owner.get(name)} and ${entry}`);
    owner.set(name, entry);
  }
}

const pkgPath = join(packageRoot, 'package.json');
const pkgText = readFileSync(pkgPath, 'utf8');
const pkg = JSON.parse(pkgText);
const conditions = (source) => {
  const base = source.slice(0, -'.ts'.length);
  return {
    'react-native': { types: `./lib/typescript/module/${base}.d.ts`, default: `./src/${source}` },
    import: { types: `./lib/typescript/module/${base}.d.ts`, default: `./lib/module/${base}.js` },
    require: {
      types: `./lib/typescript/commonjs/${base}.d.ts`,
      default: `./lib/commonjs/${base}.js`,
    },
  };
};
pkg.exports = Object.fromEntries([
  ...entries.map(([entry, file]) => [entry === '.' ? '.' : `./${entry}`, conditions(file)]),
  ['./package.json', './package.json'],
]);

const outputs = [
  [pkgPath, `${JSON.stringify(pkg, null, 2)}\n`],
  [
    join(packageRoot, 'spec/entries.generated.json'),
    `${JSON.stringify(
      {
        comment: `GENERATED by scripts/generate-entries.mjs from src/index.ts, src/router/index.ts and src/entries/*.ts. Do not edit. Each entry's value exports: "." is ${MODULE}, any other key ${MODULE}/<key>.`,
        entries: table,
      },
      null,
      2,
    )}\n`,
  ],
  [
    join(compilerSource, 'entries.generated.rs'),
    [
      '//! GENERATED by packages/bloom-language/scripts/generate-entries.mjs from packages/bloom-language/src/entries. Do not edit.',
      '',
      '/// The modules the compiler reads language views from: the root and each',
      '/// family entry (`@oxy.so/bloom-language/<family>`).',
      'pub const LANGUAGE_MODULES: &[&str] = &[',
      `    "${MODULE}",`,
      ...families.map((family) => `    "${MODULE}/${family}",`),
      '];',
      '',
    ].join('\n'),
  ],
];

outputs.push([
  join(packageRoot, 'src/__tests__/support/language.generated.ts'),
  [
    '// GENERATED by scripts/generate-entries.mjs. Do not edit.',
    '// Every entry of the language as one module, for the suites that draw every family.',
    "export * from '../../index';",
    // Named, so the router's `TabView` is the one exported over the root's view type of that name.
    `export { ${table.router.join(', ')} } from '../../router';`,
    ...families.map((family) => `export * from '../../entries/${family}';`),
    '',
  ].join('\n'),
]);

let stale = false;
for (const [path, text] of outputs) {
  let current = '';
  try {
    current = readFileSync(path, 'utf8');
  } catch {}
  if (current === text) continue;
  if (check) {
    console.error(`${path} is not current: run node scripts/generate-entries.mjs`);
    stale = true;
  } else writeFileSync(path, text);
}
if (stale) process.exit(1);
