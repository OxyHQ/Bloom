#!/usr/bin/env node
/**
 * The language's reference, generated so it never drifts from what the
 * language accepts. From `spec/language.json` (what the runtime and the
 * compiler check) and the TypeScript declarations in `src/` (each modifier's
 * signature and doc comment), it writes, at the repository root:
 *
 * - `docs/bloom-language-nodes.mdx`: every node kind, its constructors, the
 *   token sets its `size()`, `tint()`, `style()`, `shape()` and `density()`
 *   read, and its own modifiers;
 * - `docs/bloom-language-modifiers.mdx`: every modifier, its parameters with
 *   their token sets, its signature, and the nodes that take it;
 * - `docs/bloom-language-tokens.mdx`: every token set and its values;
 * - the core tokens block of `docs/bloom-language-for-agents.mdx` (the rest
 *   of that page is written by hand).
 *
 * Each item is a heading whose anchor is its name lowercased
 * (`bloom-language-modifiers.mdx#childspacing`), which the compiler's
 * messages link to.
 *
 * `--check` writes nothing and fails when a committed page differs; the
 * package's tests run it, so CI catches a spec or type change whose reference
 * was not regenerated.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { NO_TOKEN, objectsOf, tokenSetsOf, withoutComment } from './token-sets.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, '..');
const repoRoot = join(packageRoot, '../..');
const require = createRequire(join(repoRoot, 'package.json'));
const ts = require('typescript');

const spec = JSON.parse(readFileSync(join(packageRoot, 'spec/language.json'), 'utf8'));
const check = process.argv.includes('--check');

const tokenSets = tokenSetsOf(spec);
const scales = Object.fromEntries(
  Object.entries(spec.scales).map(([name, table]) => [name, withoutComment(table)]),
);
const colors = withoutComment(spec.colors);
const typeRamp = withoutComment(spec.typeRamp);
const motion = withoutComment(spec.motion);
const easing = withoutComment(spec.easing);
const loops = withoutComment(spec.loops);
const objects = objectsOf(spec);
const modifiers = withoutComment(spec.modifiers);
const nodes = withoutComment(spec.nodes);
const universal = new Set(spec.universal);
const glassValue = withoutComment(spec.glassValue);

const NODES_DOC = 'bloom-language-nodes.mdx';
const MODIFIERS_DOC = 'bloom-language-modifiers.mdx';
const TOKENS_DOC = 'bloom-language-tokens.mdx';
const GENERATED =
  '{/* GENERATED by packages/bloom-language/scripts/generate-reference.mjs from spec/language.json and the package types. Do not edit. */}';

// ── Reading the declarations ─────────────────────────────────────

/** Every source file of the package that declares API: no tests, stories or generated tables. */
function sources(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return ['__tests__', 'stories', 'generated'].includes(entry.name) ? [] : sources(path);
    }
    return /\.tsx?$/.test(entry.name) && !/\.(test|stories)\.tsx?$/.test(entry.name) ? [path] : [];
  });
}

/** A declaration's doc comment, as one paragraph of text (its first paragraph). */
function docOf(node) {
  const jsDoc = node.jsDoc ?? [];
  const last = jsDoc[jsDoc.length - 1];
  if (!last?.comment) return '';
  const text =
    typeof last.comment === 'string' ? last.comment : ts.getTextOfJSDocComment(last.comment);
  return (
    (text ?? '')
      .split(/\n\s*\n/)[0]
      .replace(/\s+/g, ' ')
      .trim() || ''
  );
}

const oneLine = (text) =>
  text.replace(/\s+/g, ' ').replace(/\(\s/g, '(').replace(/,\s\)/g, ')').trim();

/** Each export's module: the root, `/router` or its family's entry (`generate-entries.mjs`). */
const MODULE_OF = new Map(
  Object.entries(
    JSON.parse(readFileSync(join(packageRoot, 'spec/entries.generated.json'), 'utf8')).entries,
  ).flatMap(([entry, names]) =>
    names.map((name) => [
      name,
      entry === '.' ? '@oxy.so/bloom-language' : `@oxy.so/bloom-language/${entry}`,
    ]),
  ),
);

/** interface name → { members: name → [{ params, doc }], bases: [type names] } */
const interfaces = new Map();
/** constructor name → { params, returns, doc } */
const constructors = new Map();

const baseName = (typeNode, file) => typeNode.getText(file).replace(/<.*$/s, '').trim();

for (const path of sources(join(packageRoot, 'src'))) {
  const text = readFileSync(path, 'utf8');
  const file = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const exported = (node) => node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
  for (const statement of file.statements) {
    if (ts.isInterfaceDeclaration(statement)) {
      const entry = interfaces.get(statement.name.text) ?? { members: new Map(), bases: [] };
      for (const clause of statement.heritageClauses ?? []) {
        for (const type of clause.types) entry.bases.push(baseName(type.expression, file));
      }
      for (const member of statement.members) {
        if (!ts.isMethodSignature(member) || !member.name) continue;
        const name = member.name.getText(file);
        const params = oneLine(member.parameters.map((p) => p.getText(file)).join(', '));
        const list = entry.members.get(name) ?? [];
        list.push({ params, doc: docOf(member) });
        entry.members.set(name, list);
      }
      interfaces.set(statement.name.text, entry);
    } else if (ts.isTypeAliasDeclaration(statement)) {
      // `type XView = ViewModifiers<XView> & Lines<XView>`: an interface made of its parts.
      const parts = ts.isIntersectionTypeNode(statement.type)
        ? statement.type.types
        : [statement.type];
      if (!parts.every((part) => ts.isTypeReferenceNode(part))) continue;
      if (!interfaces.has(statement.name.text)) {
        interfaces.set(statement.name.text, {
          members: new Map(),
          bases: parts.map((part) => baseName(part.typeName, file)),
        });
      }
    } else if (ts.isFunctionDeclaration(statement) && statement.name && exported(statement)) {
      const name = statement.name.text;
      if (!/^[A-Z]/.test(name) || constructors.has(name)) continue;
      constructors.set(name, {
        params: oneLine(statement.parameters.map((p) => p.getText(file)).join(', ')),
        returns: statement.type ? baseName(statement.type, file) : undefined,
        doc: docOf(statement),
      });
    } else if (ts.isVariableStatement(statement) && exported(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (!ts.isIdentifier(declaration.name) || !/^[A-Z]/.test(declaration.name.text)) continue;
        // `export const Meter = meter(…) as (value: number) => MeterView`
        let type = declaration.type;
        if (!type && declaration.initializer && ts.isAsExpression(declaration.initializer)) {
          type = declaration.initializer.type;
        }
        if (!type || !ts.isFunctionTypeNode(type)) continue;
        if (constructors.has(declaration.name.text)) continue;
        constructors.set(declaration.name.text, {
          params: oneLine(type.parameters.map((p) => p.getText(file)).join(', ')),
          returns: baseName(type.type, file),
          doc: docOf(statement),
        });
      }
    }
  }
}

/** The interfaces that hold the universal modifiers: every node's base. */
const UNIVERSAL_BASES = new Set(['ViewModifiers', 'ScreenModifiers', 'ViewNode']);

/** A view type's own members: its interface's and its bases' up to the universal ones. */
function ownMembers(typeName, seen = new Set()) {
  const resolved = typeName;
  if (!interfaces.has(resolved) || seen.has(resolved) || UNIVERSAL_BASES.has(resolved))
    return new Map();
  seen.add(resolved);
  const entry = interfaces.get(resolved);
  const members = new Map();
  for (const base of entry.bases) {
    for (const [name, list] of ownMembers(base, seen)) members.set(name, list);
  }
  for (const [name, list] of entry.members) members.set(name, list);
  return members;
}

const universalMembers = new Map([
  ...(interfaces.get('ScreenModifiers')?.members ?? []),
  ...(interfaces.get('ViewModifiers')?.members ?? []),
]);

/** node kind → its own members (signature and doc per modifier). */
const nodeMembers = {};
for (const [kind, node] of Object.entries(nodes)) {
  // A kind's constructors may return different views (`Code`, `CodeBlock`): each's members count.
  const members = new Map();
  for (const name of node.constructors) {
    const returns = constructors.get(name)?.returns;
    if (!returns) continue;
    for (const [member, list] of ownMembers(returns))
      if (!members.has(member)) members.set(member, list);
  }
  nodeMembers[kind] = members;
}

// ── Writing ──────────────────────────────────────────────────────

/** Text outside code, safe in MDX: no JSX or expression braces. */
const prose = (text) =>
  text
    .split(/(`[^`]*`)/)
    .map((part, i) =>
      i % 2
        ? part
        : part
            .replace(/[{}]/g, (c) => `\\${c}`)
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;'),
    )
    .join('');

/** A code span that holds any text (backticks inside it widen the fence). */
const code = (text) => (text.includes('`') ? `\`\` ${text} \`\`` : `\`${text}\``);

const anchor = (name) => name.toLowerCase();
const tokenLink = (set, from) =>
  `[${set}](${from === TOKENS_DOC ? '' : TOKENS_DOC}#${anchor(set)})`;
const modifierLink = (name, from) =>
  `[${code(`.${name}()`)}](${from === MODIFIERS_DOC ? '' : MODIFIERS_DOC}#${anchor(name)})`;
const nodeLink = (kind, from) =>
  `[${kind}](${from === NODES_DOC ? '' : NODES_DOC}#${anchor(kind)})`;

/**
 * Tokens as a reader looks for them: the named rungs in the spec's order, then
 * the numeric ones ascending (JavaScript lists integer-like keys first).
 */
const displayOrder = (tokens) => [
  ...tokens.filter((t) => !/^-?\d+$/.test(t)),
  ...tokens.filter((t) => /^-?\d+$/.test(t)).sort((a, b) => Number(a) - Number(b)),
];

/** A token list, inline: every value of a set as a code span. */
const tokenList = (set) =>
  displayOrder(tokenSets[set] ?? [])
    .map((t) => code(`'${t}'`))
    .join(', ');

/** A typed object, its fields written out: `{ label: string, color?: dialogActionColor }`. */
function objectType(name, from) {
  const fields = Object.entries(objects[name].fields).map(([key, type]) => {
    const bare = type.replace(/\?$/, '');
    const shown = tokenSets[bare] ? tokenLink(bare, from) : code(bare);
    return `${code(`${key}${type.endsWith('?') ? '?' : ''}`)}: ${shown}`;
  });
  return `${code(name)} (${fields.join(', ')})`;
}

/** A spec parameter type, linked: a token set, an object parameter or a free value. */
function paramType(param, from) {
  const name = param.replace(/\?$/, '');
  const optional = param.endsWith('?') ? ' (optional)' : '';
  if (tokenSets[name]) return `${tokenLink(name, from)}${optional}`;
  // `[dialogButton]`: a list of a typed object.
  const listed = /^\[(.+)\]$/.exec(name);
  if (listed && objects[listed[1]]) return `a list of ${objectType(listed[1], from)}${optional}`;
  if (objects[name]?.fields) return `${objectType(name, from)}${optional}`;
  if (objects[name]) {
    return `${code(`{ ${objects[name].keys.join(', ')} }`)}, each ${tokenLink(objects[name].tokens, from)}${optional}`;
  }
  if (name === 'value') return `a value${optional}`;
  if (NO_TOKEN.includes(name)) return `a ${name}, no token${optional}`;
  return `${code(name)}${optional}`;
}

function frontmatter(title, description) {
  return ['---', `title: ${title}`, `description: ${description}`, '---', '', GENERATED, ''];
}

// The nodes page.

function nodesPage() {
  const lines = [
    ...frontmatter(
      'Bloom language nodes',
      'Every node of the Bloom language: its constructors, the token sets it reads and its own modifiers. Generated from the spec.',
    ),
    '# Bloom language nodes',
    '',
    `Every node kind the language has (${Object.keys(nodes).length}), in the spec's order: the constructors that make it, the token sets its ${code('.size()')}, ${code('.tint()')}, ${code('.style()')}, ${code('.shape()')} and ${code('.density()')} read, and the modifiers it takes beyond the universal ones. Unless a node says otherwise it also takes every universal modifier (${modifierLink('padding', NODES_DOC)}, ${modifierLink('background', NODES_DOC)}, ${modifierLink('onPress', NODES_DOC)}…; the list is in [the modifiers reference](${MODIFIERS_DOC}#universal-modifiers)).`,
    '',
    `The root, ${code('@oxy.so/bloom-language')}, holds the language's views, modifiers and values; each family of nodes is an entry of its own (${code('@oxy.so/bloom-language/<family>')}), so an app's bundle carries only the families it imports. Each node names the module it is imported from.`,
    '',
    `This page is generated from ${code('packages/bloom-language/spec/language.json')} and the package's types, the same spec the compiler checks a chain against, so what it lists is exactly what builds. For how to use them, read [the tour](bloom-language-tour.mdx).`,
    '',
    '## Index',
    '',
    '| Node | Constructors | Imported from |',
    '| --- | --- | --- |',
    ...Object.entries(nodes).map(
      ([kind, node]) =>
        `| ${nodeLink(kind, NODES_DOC)} | ${node.constructors.map((c) => code(c)).join(', ')} | ${MODULE_OF.has(node.constructors[0]) ? code(MODULE_OF.get(node.constructors[0])) : ''} |`,
    ),
    '',
    '## Nodes',
    '',
  ];
  for (const [kind, node] of Object.entries(nodes)) {
    lines.push(`### ${code(kind)}`, '');
    for (const name of node.constructors) {
      const made = constructors.get(name);
      lines.push(
        `- ${code(`${name}(${made?.params ?? '…'})`)}${made?.doc ? `: ${prose(made.doc)}` : ''}`,
      );
    }
    const module = MODULE_OF.get(node.constructors[0]);
    if (module) lines.push('', `Imported from ${code(module)}.`);
    lines.push('');
    const sets = ['size', 'tint', 'style', 'shape', 'blend']
      .filter((slot) => node[slot])
      .map(
        (slot) =>
          `- ${code(`.${slot}()`)}: ${tokenLink(node[slot], NODES_DOC)}, ${tokenList(node[slot])}`,
      );
    if (node.densities) {
      sets.push(`- ${code('.density()')}: ${node.densities.map((d) => code(`'${d}'`)).join(', ')}`);
    }
    if (sets.length) lines.push('Token sets:', '', ...sets, '');
    const members = nodeMembers[kind];
    const own = node.modifiers.filter((name) => !(node.universal !== false && universal.has(name)));
    if (own.length) {
      lines.push('Modifiers:', '');
      for (const name of own) {
        const declared =
          members.get(name) ?? (universal.has(name) ? universalMembers.get(name) : undefined);
        const signatures = declared?.map((d) => code(`(${d.params})`)).join(' or ') ?? '';
        const doc = declared?.find((d) => d.doc)?.doc;
        // A node that takes a modifier narrower than the modifier's own says what it takes.
        const narrower = node.params?.[name];
        const takes = narrower
          ? ` (here: ${narrower.length ? narrower.map((p) => paramType(p, NODES_DOC)).join('; ') : 'no parameters'})`
          : '';
        lines.push(
          `- ${modifierLink(name, NODES_DOC)}${signatures ? ` ${signatures}` : ''}${takes}${doc ? `: ${prose(doc)}` : ''}`,
        );
      }
      lines.push('');
    }
    lines.push(
      node.universal === false
        ? 'Takes only the modifiers above (no universal modifiers).'
        : own.length
          ? 'And every universal modifier.'
          : 'Takes the universal modifiers.',
      '',
    );
  }
  return lines;
}

// The modifiers page.

function modifiersPage() {
  /** modifier → the node kinds that list it (beyond the universal ones). */
  const takers = {};
  for (const [kind, node] of Object.entries(nodes)) {
    for (const name of node.modifiers) {
      takers[name] ??= [];
      takers[name].push(kind);
    }
  }
  const optedOut = Object.entries(nodes)
    .filter(([, node]) => node.universal === false)
    .map(([kind]) => kind);
  const lines = [
    ...frontmatter(
      'Bloom language modifiers',
      'Every modifier of the Bloom language: its parameters and their token sets, its signature and the nodes that take it. Generated from the spec.',
    ),
    '# Bloom language modifiers',
    '',
    `Every modifier the language has (${Object.keys(modifiers).length}). Each lists its parameters as the spec types them (a token set, an object of tokens, or a free value such as a string, a callback or a binding), its TypeScript signature where the package declares it, and which nodes take it. A token set links to its values in [the tokens reference](${TOKENS_DOC}). How modifiers combine (order is nesting, the environment, variants) is in [the tour](bloom-language-tour.mdx#modifiers-and-order).`,
    '',
    '## Universal modifiers',
    '',
    `Every node takes these, except the ${optedOut.length} nodes that take only their own (${optedOut.map((k) => nodeLink(k, MODIFIERS_DOC)).join(', ')}):`,
    '',
    spec.universal.map((name) => modifierLink(name, MODIFIERS_DOC)).join(', '),
    '',
    '## Modifiers',
    '',
  ];
  for (const [name, params] of Object.entries(modifiers)) {
    lines.push(`### ${code(name)}`, '');
    const declared =
      (universal.has(name) ? universalMembers.get(name) : undefined) ??
      Object.keys(nodes)
        .map((kind) => nodeMembers[kind].get(name))
        .find(Boolean);
    const doc = declared?.find((d) => d.doc)?.doc;
    if (doc) lines.push(prose(doc), '');
    lines.push(
      `- Parameters: ${params.length ? params.map((p) => paramType(p, MODIFIERS_DOC)).join('; ') : 'none'}`,
    );
    if (declared) {
      const signatures = [...new Set(declared.map((d) => `.${name}(${d.params})`))];
      lines.push(`- Signature: ${signatures.map(code).join(' or ')}`);
    }
    const by = takers[name] ?? [];
    if (universal.has(name)) {
      lines.push(
        `- Taken by: every node (universal)${by.length ? `, and ${by.map((k) => nodeLink(k, MODIFIERS_DOC)).join(', ')}` : ''}`,
      );
    } else {
      lines.push(
        `- Taken by: ${by.length ? by.map((k) => nodeLink(k, MODIFIERS_DOC)).join(', ') : 'no node'}`,
      );
    }
    const narrower = Object.entries(nodes).filter(([, node]) => node.params?.[name]);
    if (narrower.length) {
      lines.push(
        `- Narrower on: ${narrower
          .map(
            ([kind, node]) =>
              `${nodeLink(kind, MODIFIERS_DOC)} (${node.params[name].map((p) => paramType(p, MODIFIERS_DOC)).join('; ') || 'no parameters'})`,
          )
          .join(', ')}`,
      );
    }
    if (name === 'glass') {
      lines.push(
        `- A glass value's methods: ${Object.entries(glassValue)
          .map(
            ([method, params]) =>
              `${code(`.${method}()`)} (${params.length ? params.map((p) => paramType(p, MODIFIERS_DOC)).join('; ') : 'no parameters'})`,
          )
          .join(', ')}`,
      );
    }
    if (spec.variants.modifiers.includes(name)) {
      lines.push(
        `- Varies under ${code('.when(condition, v => v…)')} ([variants](bloom-language-tour.mdx#variants)).`,
      );
    }
    for (const param of params) {
      const set = param.replace(/\?$/, '');
      const tokens = tokenSets[set] ?? (objects[set] ? tokenSets[objects[set].tokens] : undefined);
      if (tokens && tokens.length <= 40) {
        lines.push(
          `- ${code(set)} tokens: ${tokenList(tokenSets[set] ? set : objects[set].tokens)}`,
        );
      } else if (tokens) {
        lines.push(
          `- ${code(set)} tokens: ${tokens.length}, listed under ${tokenLink(tokenSets[set] ? set : objects[set].tokens, MODIFIERS_DOC)}`,
        );
      }
    }
    lines.push('');
  }
  return lines;
}

// The tokens page.

/** What a token is worth, when the spec gives it a value (a scale's number, a role's variable…). */
function tokenValue(set, token) {
  if (scales[set] && token in scales[set]) return JSON.stringify(scales[set][token]);
  if (set === 'color' && colors[token]) {
    const [native, css] = colors[token];
    // The surface fill has no web value: the leaf that paints it reads the surface it is on.
    if (css === null) return `${native} (the surface the view is on)`;
    return `${native} / ${css.startsWith('#') || css === 'transparent' ? css : `var(--${css})`}`;
  }
  if (set === 'typeRamp' && typeRamp[token]) {
    const [size, lineHeight, letterSpacing, weight] = typeRamp[token];
    return `${size}/${lineHeight}, tracking ${letterSpacing}, weight ${weight}`;
  }
  if ((set === 'motion' || set === 'timedMotion') && motion[token]) {
    const m = motion[token];
    return m.response !== undefined
      ? `spring, response ${m.response}, damping ${m.dampingRatio}`
      : `${m.duration} ms, ${m.easing}`;
  }
  if (set === 'loop' && loops[token]) return `${loops[token].frames.length} frames`;
  return undefined;
}

function tokensPage() {
  const lines = [
    ...frontmatter(
      'Bloom language tokens',
      'Every token set of the Bloom language and its values. Generated from the spec.',
    ),
    '# Bloom language tokens',
    '',
    `Every value a modifier takes is a token of a named set: a Bloom rung, never a pixel or a colour. A numeric token (${code("'44'")}) is an exact value apps write, named by its value. An app adds its own space, size, leading, motion and colour tokens with ${code('defineTokens')} ([tokens in the tour](bloom-language-tour.mdx#tokens)). The sets below are the ones the compiler checks a literal against (${Object.keys(tokenSets).length}); where the spec gives a token a value (points, a colour role's theme key and CSS variable, a motion's timing) it is shown.`,
    '',
    '## Index',
    '',
    Object.keys(tokenSets)
      .map((set) => tokenLink(set, TOKENS_DOC))
      .join(', '),
    '',
    '## Sets',
    '',
  ];
  const easingNames = Object.keys(easing);
  for (const [set, tokens] of Object.entries(tokenSets)) {
    lines.push(`### ${code(set)}`, '');
    const valued = displayOrder(tokens).map((t) => [t, tokenValue(set, t)]);
    if (valued.some(([, v]) => v !== undefined)) {
      lines.push('| Token | Value |', '| --- | --- |');
      for (const [t, v] of valued)
        lines.push(
          `| ${code(`'${t}'`)} | ${v === undefined ? '' : prose(v).replace(/\|/g, '\\|')} |`,
        );
    } else {
      lines.push(tokenList(set));
    }
    const users = Object.entries(modifiers)
      .filter(([, params]) =>
        params.some((p) => {
          const n = p.replace(/\?$/, '');
          return n === set || objects[n]?.tokens === set;
        }),
      )
      .map(([name]) => modifierLink(name, TOKENS_DOC));
    const readers = Object.entries(nodes)
      .filter(([, node]) =>
        ['size', 'tint', 'style', 'shape', 'blend'].some((slot) => node[slot] === set),
      )
      .map(([kind]) => nodeLink(kind, TOKENS_DOC));
    const own = Object.entries(nodes).flatMap(([kind, node]) =>
      Object.entries(node.params ?? {})
        .filter(([, params]) => params.some((p) => p.replace(/\?$/, '') === set))
        .map(([name]) => `${nodeLink(kind, TOKENS_DOC)} ${code(`.${name}()`)}`),
    );
    const glassUsers = Object.entries(glassValue)
      .filter(([, params]) => params.some((p) => p.replace(/\?$/, '') === set))
      .map(([name]) => code(`regular.${name}()`));
    lines.push('');
    if (set === 'colorRole') {
      lines.push(
        `A colour role alone: never at an opacity, nor an app colour. What a node paints by the role's name takes it.`,
        '',
      );
    }
    if (set === 'color') {
      lines.push(
        `A colour token is a role above (on native the theme's colour named first, on the web the CSS variable), a role at an opacity of the ${tokenLink('opacity', TOKENS_DOC)} scale (${code("'primary/10'")}), or an app colour from ${code('defineTokens({ color })')}.`,
        '',
      );
    }
    if (users.length) lines.push(`Taken by: ${users.join(', ')}.`, '');
    if (own.length) lines.push(`Taken by these nodes' own parameters: ${own.join(', ')}.`, '');
    if (glassUsers.length) lines.push(`Taken by a glass value's ${glassUsers.join(', ')}.`, '');
    if (readers.length)
      lines.push(
        `Read by these nodes' ${code('.size()')}/${code('.tint()')}/${code('.style()')}/${code('.shape()')}: ${readers.join(', ')}.`,
        '',
      );
  }
  lines.push(
    '## Easing curves',
    '',
    `The curves a motion token names: ${easingNames.map((e) => code(e)).join(', ')}.`,
    '',
  );
  return lines;
}

