/**
 * Writes Sources/ColorEngine/PresetLabels.generated.bloom: the seeds of the built-in presets that
 * declare a white label (src/theme/color-presets.ts), which the colour policy reads
 * (`declaresWhiteLabel`). Data from the registry, never typed by hand; test/slice3.test.ts fails
 * when the file is stale. Run: bun scripts/generate-preset-labels.ts (packages/bloom-theme-engine).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { APP_COLOR_NAMES, APP_COLOR_PRESETS } from '../../../src/theme/color-presets';

export const PRESET_LABELS_FILE = join(
  __dirname,
  '..',
  'Sources',
  'ColorEngine',
  'PresetLabels.generated.bloom',
);

export function presetLabelsSource(): string {
  const seeds = APP_COLOR_NAMES.filter((name) => APP_COLOR_PRESETS[name].label === 'white').map(
    (name) => APP_COLOR_PRESETS[name].hex.toLowerCase(),
  );
  return [
    '// Generated by scripts/generate-preset-labels.ts from src/theme/color-presets.ts. Do not edit.',
    '',
    '/// The seeds (lowercase `#rrggbb`) of the built-in presets that declare a white label.',
    `let WHITE_LABEL_SEEDS: [String] = [${seeds.map((s) => `"${s}"`).join(', ')}]`,
    '',
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(PRESET_LABELS_FILE, presetLabelsSource());
  console.log(`[generate-preset-labels] wrote ${PRESET_LABELS_FILE}`);
}
