#!/usr/bin/env node
// Splits the synced glass engine into two Gradle projects (run by sync-from-upstream.sh, after Bloom's patches):
//
// - android-engine/: the engine, free of React Native and Expo. The glass renderer, its shaders and fields, the
//   window backdrop and its lenses, the jelly and the springs, the press feedback, and the four configuration
//   records as plain Kotlin classes. Bloom's native runtime (Compose, no JavaScript) draws its material through it.
// - android/: the Expo adapter. The menu, the chrome and the surface nodes, the Expo modules, and the records the
//   JavaScript props arrive in (GlassMenuConfigProps and the others, Expo Records), turned into the engine's by
//   toEngine() where the module receives them.
//
// The engine's declarations are public (upstream marks them `internal`, which would hide them from the adapter, now
// another module). It fails if the engine imports React Native or Expo, or if an upstream line it rewrites moved.
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const adapter = path.join(here, 'android/src/main/java/so/oxy/bloom/glassmenu');
const engine = path.join(here, 'android-engine/src/main/java/so/oxy/bloom/glassmenu');

/** The engine: whole directories, then single files (paths under glassmenu/). */
const ENGINE_DIRS = ['backdrop', 'field', 'render'];
const ENGINE_FILES = [
  'motion/GlassJelly.kt',
  'motion/GlassSpring.kt',
  'overlay/GlassFeedback.kt',
  'chrome/StaticGlassCache.kt',
];
/** The records the engine reads, in dependency order (a record's fields may name the ones before it). */
const RECORDS = [
  'GlassShrinkRecord',
  'GlassAbsorbRecord',
  'GlassMenuConfigRecord',
  'GlassTriggerConfigRecord',
];

function fail(message) {
  console.error(`split-engine: ${message}`);
  process.exit(1);
}

function move(rel) {
  const from = path.join(adapter, rel);
  const to = path.join(engine, rel);
  if (!fs.existsSync(from)) fail(`${rel} is not in the synced tree`);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.renameSync(from, to);
}

fs.rmSync(path.join(here, 'android-engine/src'), { recursive: true, force: true });
for (const dir of ENGINE_DIRS) move(dir);
for (const file of ENGINE_FILES) move(file);

// The records: plain classes in the engine (each field a constructor parameter with its default), Expo Records in
// the adapter (`…Props`), and toEngine() from one to the other.
const props = [];
for (const name of RECORDS) {
  const file = path.join(adapter, 'records', `${name}.kt`);
  if (!fs.existsSync(file)) fail(`records/${name}.kt is not in the synced tree`);
  const text = fs.readFileSync(file, 'utf8');
  fs.rmSync(file);
  const fields = [];
  const lines = [];
  for (const line of text.slice(text.indexOf('{') + 1, text.lastIndexOf('}')).split('\n')) {
    const field = line.match(/^\s*@Field val (\w+): ([\w?.<>]+) = (.+)$/);
    if (field) {
      fields.push({ name: field[1], type: field[2], value: field[3] });
      lines.push(`  val ${field[1]}: ${field[2]} = ${field[3]},`);
    } else if (/^\s*\/\//.test(line)) {
      lines.push(line);
    } else if (line.trim()) {
      fail(`records/${name}.kt: a line the split does not know: ${line.trim()}`);
    }
  }
  const imports = text.includes('Color') ? 'import android.graphics.Color\n\n' : '';
  fs.mkdirSync(path.join(engine, 'records'), { recursive: true });
  fs.writeFileSync(
    path.join(engine, 'records', `${name}.kt`),
    `// Generated by split-engine.mjs from the upstream Expo record: the engine's plain configuration.\n` +
      `package so.oxy.bloom.glassmenu.records\n\n${imports}class ${name}(\n${lines.join('\n')}\n)\n`,
  );
  const propsName = name.replace(/Record$/, 'Props');
  const toProps = (type) => type.replace(/(Glass\w+)Record/, '$1Props');
  const convert = (f) => {
    const nested = f.type.match(/^(Glass\w+)Record(\?)?$/);
    if (!nested) return `${f.name} = ${f.name}`;
    return `${f.name} = ${f.name}${nested[2] ? '?' : ''}.toEngine()`;
  };
  props.push(
    `class ${propsName} : Record {\n${fields.map((f) => `  @Field val ${f.name}: ${toProps(f.type)} = ${f.value}`).join('\n')}\n}\n\n` +
      `fun ${propsName}.toEngine() = ${name}(\n${fields.map((f) => `  ${convert(f)},`).join('\n')}\n)\n`,
  );
}
fs.writeFileSync(
  path.join(adapter, 'records', 'GlassConfigProps.kt'),
  `// Generated by split-engine.mjs: the configuration records the JavaScript props arrive in (Expo Records), and\n` +
    `// toEngine() to the engine's plain classes.\npackage so.oxy.bloom.glassmenu.records\n\n` +
    `import android.graphics.Color\nimport expo.modules.kotlin.records.Field\nimport expo.modules.kotlin.records.Record\n\n` +
    props.join('\n'),
);

// The module takes the Props and hands the engine its records.
const moduleFile = path.join(adapter, 'GlassMenuAndroidModule.kt');
let moduleText = fs.readFileSync(moduleFile, 'utf8');
for (const [record, prop] of [
  ['GlassMenuConfigRecord', 'view.config'],
  ['GlassTriggerConfigRecord', 'view.triggerConfig'],
]) {
  const propsName = record.replace(/Record$/, 'Props');
  const from = new RegExp(
    `config: ${record}\\? ->\\n(\\s*)${prop.replace('.', '\\.')} = config \\?: ${record}\\(\\)`,
  );
  if (!from.test(moduleText)) fail(`GlassMenuAndroidModule.kt: the ${prop} prop moved`);
  moduleText = moduleText.replace(
    from,
    `config: ${propsName}? ->\n$1${prop} = config?.toEngine() ?: ${record}()`,
  );
  moduleText = moduleText.replace(
    `import so.oxy.bloom.glassmenu.records.${record}\n`,
    `import so.oxy.bloom.glassmenu.records.${record}\nimport so.oxy.bloom.glassmenu.records.${propsName}\n`,
  );
}
moduleText = moduleText.replace(
  'import so.oxy.bloom.glassmenu.records.GlassMenuConfigProps\n',
  'import so.oxy.bloom.glassmenu.records.GlassMenuConfigProps\nimport so.oxy.bloom.glassmenu.records.toEngine\n',
);
fs.writeFileSync(moduleFile, moduleText);

// The engine's declarations are public, and it imports neither React Native nor Expo.
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}
for (const file of walk(engine)) {
  const text = fs.readFileSync(file, 'utf8');
  if (/^import (com\.facebook|expo)\./m.test(text))
    fail(`${path.relative(here, file)} imports React Native or Expo`);
  fs.writeFileSync(
    file,
    text.replace(
      /\binternal (?=(?:@\w+ )*(?:abstract |open |data |enum |inline |const |lateinit |override )*(?:class|object|interface|fun|val|var|constructor)\b)/g,
      '',
    ),
  );
}
console.log(`split-engine: ${walk(engine).length} engine files in android-engine/`);
