#!/usr/bin/env python3
"""Writes Bloom's glyphs from its icon sources (src/icons) for the native runtimes:

    icons.py <bloom checkout> <Icons.kt>             the glyphs the Android bench uses
    icons.py <bloom checkout> --swift <Glyphs.swift> every glyph, for BloomUI on iOS

Each glyph keeps its path data, viewBox, stroke width, cap and join (a stroked glyph draws
only its stroke; every path fills even-odd, as glyph-svg.tsx draws it). The Swift output
names each glyph as `.bloom` writes it (`Icon(.verifiedBadgeFill)`), by the same rule as
crates/lang/src/bloomui.rs's `icon_component`."""
import re, sys, pathlib
root = pathlib.Path(sys.argv[1])  # the Bloom checkout


def glyph_of(text):
    """(paths, width, height, stroke width or None, cap, join) of a createSinglePathSVG file."""
    paths = re.findall(r"\bpath:\s*'([^']+)'", text)
    block = re.search(r"\bpaths:\s*\[([^\]]*)\]", text, re.S)
    if block:
        paths += re.findall(r"'([^']+)'", block.group(1))
    box = re.search(r"viewBox:\s*'([^']+)'", text)
    stroke = re.search(r"strokeWidth:\s*([0-9.]+)", text)
    cap = re.search(r"strokeLinecap:\s*'(\w+)'", text)
    join = re.search(r"strokeLinejoin:\s*'(\w+)'", text)
    vb = box.group(1).split() if box else ["0", "0", "24", "24"]
    sw = float(stroke.group(1)) if stroke and float(stroke.group(1)) > 0 else None
    return paths, vb[2], vb[3], sw, cap.group(1) if cap else "butt", join.group(1) if join else "miter"


# The language's own glyphs (crates/lang/src/bloomui.rs OWN_ICONS) and its aliases.
OWN_ICONS = ["Like", "LikeFill", "Reply", "Repost", "MediaAttachment", "GifAttachment"]
ALIASES = {"verified": "verifiedBadge", "verifiedFill": "verifiedBadgeFill"}


def lower_first(s):
    return s[0].lower() + s[1:]


def swift(out):
    entries = {}  # Bloom name -> (component, glyph)
    for f in sorted((root / "src/icons/remix").glob("Ri*.tsx")):
        component = f.stem
        body = component[2:]
        g = glyph_of(f.read_text())
        if not g[0]:
            continue
        if body.endswith("Line"):
            names = [lower_first(body[:-4]), lower_first(body)]
        else:
            names = [lower_first(body)]
        for n in names:
            entries.setdefault(n, (component, g))
    for name in OWN_ICONS:
        f = root / "src/icons/social" / f"{name}Icon.tsx"
        g = glyph_of(f.read_text())
        entries[lower_first(name)] = (f"{name}Icon", g)
    for alias, target in ALIASES.items():
        if target in entries:
            entries[alias] = entries[target]
    kw = {"repeat", "default", "import", "return", "switch", "case", "in", "is", "as", "for", "if", "else", "func", "let", "var", "class", "struct", "enum", "protocol", "extension", "operator", "where", "while", "do", "catch", "try", "throw", "true", "false", "nil", "self", "super", "init", "static", "public", "private", "internal", "subscript", "typealias", "defer", "guard", "break", "continue", "fallthrough", "inout", "associatedtype", "deinit", "fileprivate", "open", "rethrows", "throws", "Type", "Any"}
    lines = ["// Generated by crates/native/scripts/icons.py from Bloom's src/icons (Remix Icon, Remix",
             "// Icon License 1.0, and Bloom's own). Do not edit.", "",
             "extension Glyph {"]
    seen = {}
    for name in sorted(entries):
        component, (paths, w, h, sw, cap, join) = entries[name]
        ident = f"`{name}`" if name in kw else name
        if component in seen:
            lines.append(f"  /// `{component}`.\n  public static var {ident}: Glyph {{ .{seen[component]} }}")
            continue
        seen[component] = ident
        joined = ", ".join('"' + p + '"' for p in paths)
        stroke = "nil" if sw is None else repr(sw)
        lines.append(f"  /// `{component}`.\n  public static let {ident} = Glyph(\n    name: \"{component}\", paths: [{joined}], width: {w}, height: {h}, strokeWidth: {stroke}, cap: .{cap}, join: .{join})")
    lines.append("}\n")
    out.write_text("\n".join(lines))
    print(f"icons.py: {len(seen)} glyphs, {len(entries)} names")


if sys.argv[2] == "--swift":
    swift(pathlib.Path(sys.argv[3]))
    sys.exit(0)
out = pathlib.Path(sys.argv[2])
glyphs = {  # Bloom 2.0 icon name -> source file
    "like": "social/LikeIcon.tsx", "likeFill": "social/LikeFillIcon.tsx",
    "reply": "social/ReplyIcon.tsx", "repost": "social/RepostIcon.tsx",
    "share": "social/ShareIcon.tsx", "verifiedBadgeFill": "remix/RiVerifiedBadgeFill.tsx",
    "home": "remix/RiHomeLine.tsx", "homeFill": "remix/RiHomeFill.tsx",
    "settings": "remix/RiSettings3Line.tsx", "settingsFill": "remix/RiSettings3Fill.tsx",
}
lines = ["// Generated by crates/native/scripts/icons.py from Bloom's src/icons. Do not edit.",
         "package so.oxy.bloom.ui", "", "object Icons {"]
for name, rel in glyphs.items():
    text = (root / "src/icons" / rel).read_text()
    paths = re.findall(r"path:\s*'([^']+)'", text) or re.findall(r'd:\s*\'([^\']+)\'', text)
    box = re.search(r"viewBox:\s*'([^']+)'", text)
    stroke = re.search(r"strokeWidth:\s*([0-9.]+)", text)
    vb = box.group(1).split() if box else ["0", "0", "24", "24"]
    sw = f"{stroke.group(1)}f" if stroke else "null"
    joined = ", ".join('"' + p + '"' for p in paths)
    lines.append(f"  val {name} = IconData(listOf({joined}), {vb[2]}f, {vb[3]}f, {sw})")
lines += ["", "  /** A tab's icon by name, and its selected form. */",
          "  fun named(name: String): Pair<IconData, IconData> = when (name) {",
          "    \"home\" -> home to homeFill", "    \"settings\" -> settings to settingsFill",
          "    else -> home to homeFill", "  }", "}", ""]
out.write_text("\n".join(lines))
