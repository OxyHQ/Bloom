#!/usr/bin/env python3
"""Writes runtime/android/so/oxy/bloom/ui/Icons.kt from Bloom's icon sources (src/icons):
the glyphs the runtime's programs use, as path data, each named as the language names it and
resolved to its component as the checker resolves it (`bloomui::icon_component`: Bloom's own
social glyphs by their name, every other a Remix icon, `Line` unless it says `Fill`).
A real backend writes the glyphs a program uses; this list is the bench's and the M1 feed's.

Usage: icons.py <Bloom checkout> <Icons.kt>"""
import re, sys, pathlib
root = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
# The checker's OWN_ICONS and ICON_ALIASES (crates/lang/src/bloomui.rs).
OWN = {"Like", "LikeFill", "Reply", "Repost", "MediaAttachment", "GifAttachment",
       "Share", "Bookmark", "BookmarkFill", "Menu"}
ALIASES = {"verified": "verifiedBadge", "verifiedFill": "verifiedBadgeFill"}
NAMES = ["like", "likeFill", "reply", "repost", "share", "bookmark", "bookmarkFill",
         "verifiedBadgeFill", "moreFill", "repeat2", "sendPlane", "volumeMute", "volumeUp",
         "play", "playFill", "home", "homeFill", "settings", "settingsFill"]

def component(name):
    name = ALIASES.get(name, name)
    pascal = re.sub(r"[-_](.)", lambda m: m.group(1).upper(), name)
    pascal = pascal[0].upper() + pascal[1:]
    if pascal in OWN:
        return f"{pascal}Icon", root / "src/icons/social" / f"{pascal}Icon.tsx"
    comp = f"Ri{pascal}" if pascal.endswith(("Fill", "Line")) else f"Ri{pascal}Line"
    return comp, root / "src/icons/remix" / f"{comp}.tsx"

lines = ["// Generated by crates/native/scripts/icons.py from Bloom's src/icons. Do not edit.",
         "package so.oxy.bloom.ui", "", "object Icons {"]
names = []
for name in NAMES:
    comp, path = component(name)
    if name in ("home", "homeFill", "settings", "settingsFill"):
        comp, path = {"home": ("RiHomeLine", None), "homeFill": ("RiHomeFill", None),
                      "settings": ("RiSettings3Line", None), "settingsFill": ("RiSettings3Fill", None)}[name]
        path = root / "src/icons/remix" / f"{comp}.tsx"
    if not path.is_file():
        sys.exit(f"icons.py: {name}: {path} not found")
    text = path.read_text()
    paths = re.findall(r"path:\s*'([^']+)'", text) or re.findall(r"d:\s*'([^']+)'", text)
    box = re.search(r"viewBox:\s*'([^']+)'", text)
    stroke = re.search(r"strokeWidth:\s*([0-9.]+)", text)
    vb = box.group(1).split() if box else ["0", "0", "24", "24"]
    sw = f"{stroke.group(1)}f" if stroke else "null"
    joined = ", ".join('"' + p + '"' for p in paths)
    lines.append(f"  /** `.{name}`: {comp}. */")
    lines.append(f"  val {name} = IconData(listOf({joined}), {vb[2]}f, {vb[3]}f, {sw})")
    names.append(name)
# An action's glyph when it is on: its `Fill` form, where the set has one.
pairs = [(n, n + "Fill") for n in names if n + "Fill" in names]
lines += ["", "  /** The glyph an action draws while it is on: the glyph's `Fill` form, else the glyph. */",
          "  fun active(icon: IconData): IconData = when {"]
lines += [f"    icon === {a} -> {b}" for a, b in pairs]
lines += ["    else -> icon", "  }",
          "", "  /** A tab's icon by name, and its selected form. */",
          "  fun named(name: String): Pair<IconData, IconData> = when (name) {",
          "    \"home\" -> home to homeFill", "    \"settings\" -> settings to settingsFill",
          "    else -> home to homeFill", "  }", "}", ""]
out.write_text("\n".join(lines))
