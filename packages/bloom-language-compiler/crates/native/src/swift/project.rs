//! The Xcode project around the swiftui output (`--ios-project <dir>`): what `bloom build ios
//! --target native` writes, a pure SwiftUI app with no JavaScript.
//!
//! ```text
//! <dir>/project.yml              XcodeGen: the iOS app target, Info.plist, fonts, the URL scheme
//! <dir>/Package.swift            the app's Bloom modules, one Swift module each
//! <dir>/Sources/<Module>/*.swift the emitted code
//! <dir>/BloomRuntime/            the runtime (Bloom, BloomTheme, BloomUI), copied
//! <dir>/App/<Name>App.swift      `@main`: the package's `App` view in Bloom's theme
//! <dir>/App/Fonts/*.ttf          Inter, BlomusModernus, JetBrains Mono (src/fonts/assets)
//! ```
//!
//! On the Mac: `xcodegen generate` then `xcodebuild` (bench/native/ios-build.sh). The runtime
//! and the fonts are copied from this checkout, as the Android project embeds its runtime.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use bloom_lang::ast::ImportKind;

use crate::{Emitted, Program};

/// The iOS release the app targets (Package.bloom's `.iOS(17)`): `@Observable`, `Layout`,
/// two-argument `onChange`; Liquid Glass from iOS 26, with the material's fallback before it.
pub const IOS_DEPLOYMENT: &str = "17.0";

/// Bloom's fonts on iOS (src/fonts/font-assets.native.ts).
const FONTS: &[&str] = &[
    "InterVariable.ttf",
    "BlomusModernus-Regular.ttf",
    "BlomusModernus-Bold.ttf",
    "JetBrainsMono-Variable.ttf",
];

fn write(path: &Path, text: &str) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

fn copy_dir(from: &Path, to: &Path) -> Result<(), String> {
    std::fs::create_dir_all(to).map_err(|e| format!("{}: {e}", to.display()))?;
    let entries = std::fs::read_dir(from).map_err(|e| format!("{}: {e}", from.display()))?;
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        if matches!(name.to_str(), Some(".build" | ".swiftpm" | "Tests" | "Stubs")) {
            continue;
        }
        let target = to.join(&name);
        if path.is_dir() {
            copy_dir(&path, &target)?;
        } else {
            std::fs::copy(&path, &target).map_err(|e| format!("{}: {e}", path.display()))?;
        }
    }
    Ok(())
}

/// The runtime package in this checkout.
pub fn runtime_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("runtime/ios")
}

/// Bloom's fonts in this checkout.
fn fonts_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../../src/fonts/assets")
}

/// The module whose `App` view is the app (as on Android: the module named like the package).
fn app_module(program: &Program) -> String {
    program
        .modules
        .iter()
        .find(|m| m.name == program.name)
        .or_else(|| program.modules.iter().find(|m| m.files.iter().any(|f| f.source.contains("struct App:"))))
        .map(|m| m.name.clone())
        .unwrap_or_else(|| program.name.clone())
}

/// Each module's dependencies on the package's other modules: what its files import.
fn module_dependencies(program: &Program) -> Vec<(String, BTreeSet<String>)> {
    let names: BTreeSet<String> = program.modules.iter().map(|m| m.name.clone()).collect();
    program
        .modules
        .iter()
        .map(|m| {
            let mut deps = BTreeSet::new();
            for file in &m.files {
                for import in &file.ast.imports {
                    if let ImportKind::Module(path) = &import.kind
                        && let Some(first) = path.first()
                        && names.contains(&first.name)
                        && first.name != m.name
                    {
                        deps.insert(first.name.clone());
                    }
                }
            }
            (m.name.clone(), deps)
        })
        .collect()
}

/// `Package.swift`: one target per Bloom module, over the runtime.
pub fn package_swift(program: &Program) -> String {
    let app = app_module(program);
    let mut targets = String::new();
    for (name, deps) in module_dependencies(program) {
        let mut list: Vec<String> = deps.iter().map(|d| format!("\"{d}\"")).collect();
        for product in ["Bloom", "BloomTheme", "BloomUI"] {
            list.push(format!(".product(name: \"{product}\", package: \"BloomRuntime\")"));
        }
        let _ = writeln!(
            targets,
            "    .target(name: \"{name}\", dependencies: [{}], path: \"Sources/{name}\"),",
            list.join(", ")
        );
    }
    format!(
        "// swift-tools-version: 6.0\n// Generated by bloom-native --target swiftui. Do not edit.\nimport PackageDescription\n\nlet package = Package(\n  name: \"{name}Modules\",\n  platforms: [.iOS(.v17), .macOS(.v14)],\n  products: [.library(name: \"{app}\", targets: [\"{app}\"])],\n  dependencies: [.package(path: \"BloomRuntime\")],\n  targets: [\n{targets}  ]\n)\n",
        name = program.name
    )
}

/// The URL scheme deep links open the app with: the app id's last part (`nativebench`).
fn url_scheme(id: &str) -> String {
    id.split('.').rev().find(|p| !matches!(*p, "swiftui" | "ios" | "rn")).unwrap_or(id).to_lowercase()
}

pub fn project_yml(program: &Program, id: &str) -> String {
    let app = app_module(program);
    let fonts: Vec<String> = FONTS.iter().map(|f| format!("          - Fonts/{f}")).collect();
    format!(
        "# Generated by bloom-native --target swiftui. Do not edit. `xcodegen generate` writes the\n# Xcode project from it (bench/native/ios-build.sh).\nname: {name}\noptions:\n  deploymentTarget:\n    iOS: \"{IOS_DEPLOYMENT}\"\n  createIntermediateGroups: true\npackages:\n  Modules:\n    path: .\ntargets:\n  {name}:\n    type: application\n    platform: iOS\n    sources:\n      - path: App\n    dependencies:\n      - package: Modules\n        product: {app}\n    settings:\n      base:\n        PRODUCT_BUNDLE_IDENTIFIER: {id}\n        PRODUCT_NAME: {name}\n        SWIFT_VERSION: \"6.0\"\n        TARGETED_DEVICE_FAMILY: \"1\"\n        CODE_SIGN_STYLE: Automatic\n        DEVELOPMENT_TEAM: ${{BLOOM_IOS_TEAM}}\n        ENABLE_USER_SCRIPT_SANDBOXING: YES\n        SWIFT_OPTIMIZATION_LEVEL: \"-O\"\n      configs:\n        Debug:\n          SWIFT_OPTIMIZATION_LEVEL: \"-Onone\"\n    info:\n      path: App/Info.plist\n      properties:\n        CFBundleDisplayName: {name}\n        CFBundleShortVersionString: \"0.1.0\"\n        CFBundleVersion: \"1\"\n        UILaunchScreen: {{}}\n        UIApplicationSceneManifest:\n          UIApplicationSupportsMultipleScenes: false\n        UIAppFonts:\n{fonts}\n        CFBundleURLTypes:\n          - CFBundleURLSchemes: [{scheme}]\n  {name}UITests:\n    type: bundle.ui-testing\n    platform: iOS\n    sources:\n      - path: UITests\n    dependencies:\n      - target: {name}\n    settings:\n      base:\n        PRODUCT_BUNDLE_IDENTIFIER: {id}.uitests\n        SWIFT_VERSION: \"6.0\"\n        GENERATE_INFOPLIST_FILE: YES\n        CODE_SIGN_STYLE: Automatic\n        DEVELOPMENT_TEAM: ${{BLOOM_IOS_TEAM}}\n        TEST_TARGET_NAME: {name}\nschemes:\n  {name}:\n    build:\n      targets:\n        {name}: all\n    run:\n      config: Release\n    test:\n      config: Release\n      targets:\n        - {name}UITests\n",
        name = program.name,
        fonts = fonts.join("\n"),
        scheme = url_scheme(id),
    )
}

fn app_swift(program: &Program) -> String {
    let app = app_module(program);
    format!(
        "// Generated by bloom-native --target swiftui. Do not edit.\n//\n// The app: the package's `App` view, in Bloom's theme (the `oxy` preset, the system's scheme).\nimport SwiftUI\nimport BloomUI\nimport {app}\n\n@main\nstruct {name}Main: SwiftUI.App {{\n  var body: some Scene {{\n    WindowGroup {{\n      BloomThemeProvider {{\n        {app}.App()\n      }}\n    }}\n  }}\n}}\n",
        name = program.name
    )
}

/// The bench as XCTest measures it, the same four numbers as the Android bench
/// (bench/native/bench.sh): cold start, scroll hitches over 30 fast flings, memory after the
/// feed, and the toggle (the app's own `BENCH toggle <ms>` lines, from `.onChange`).
fn bench_tests(program: &Program) -> String {
    format!(
        r#"// Generated by bloom-native --target swiftui. Do not edit.
//
// `xcodebuild test -scheme {name} -destination …` (bench/native/swiftui-bench.sh), Release.
import XCTest

final class {name}Bench: XCTestCase {{
  override func setUp() {{ continueAfterFailure = false }}

  /// Cold start, to the first frame the app answers in (XCTApplicationLaunchMetric), 5 runs.
  func testColdStart() {{
    let options = XCTMeasureOptions()
    options.iterationCount = 5
    measure(metrics: [XCTApplicationLaunchMetric(waitUntilResponsive: true)], options: options) {{
      XCUIApplication().launch()
    }}
  }}

  /// 30 fast flings down the 500 rows: hitch time ratio and frame rate (the scroll's
  /// signposts), and memory.
  func testFeedScroll() {{
    let app = XCUIApplication()
    app.launch()
    let list = app.collectionViews.firstMatch
    XCTAssertTrue(list.waitForExistence(timeout: 10))
    let options = XCTMeasureOptions()
    options.iterationCount = 5
    measure(metrics: [XCTOSSignpostMetric.scrollingAndDecelerationMetric, XCTMemoryMetric(application: app)], options: options) {{
      for _ in 0..<30 {{ list.swipeUp(velocity: .fast) }}
    }}
  }}

  /// The Settings tab, then 20 taps on the first switch, 1.2 s apart; the app prints
  /// `BENCH toggle <ms>` for each (handler to committed update), in its console.
  func testToggle() {{
    let app = XCUIApplication()
    app.launch()
    app.tabBars.buttons.element(boundBy: 1).tap()
    let toggle = app.buttons["Push notifications"]
    XCTAssertTrue(toggle.waitForExistence(timeout: 10))
    for _ in 0..<20 {{
      toggle.tap()
      Thread.sleep(forTimeInterval: 1.2)
    }}
  }}
}}
"#,
        name = program.name
    )
}

/// Writes the project at `dir` around `emitted` (the backend's files, `Sources/<Module>/…`).
pub fn write_project(dir: &Path, program: &Program, emitted: &[Emitted], id: &str) -> Result<(), String> {
    write(&dir.join("Package.swift"), &package_swift(program))?;
    write(&dir.join("project.yml"), &project_yml(program, id))?;
    write(&dir.join(format!("App/{}App.swift", program.name)), &app_swift(program))?;
    for file in emitted {
        write(&dir.join(&file.path), &file.text)?;
    }
    copy_dir(&runtime_dir(), &dir.join("BloomRuntime"))?;
    let fonts = fonts_dir();
    for font in FONTS {
        let to = dir.join("App/Fonts").join(font);
        if let Some(parent) = to.parent() {
            std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        std::fs::copy(fonts.join(font), &to).map_err(|e| format!("{}: {e}", fonts.join(font).display()))?;
    }
    write(&dir.join(format!("UITests/{}Bench.swift", program.name)), &bench_tests(program))?;
    write(&dir.join(".gitignore"), "*.xcodeproj/\n.build/\nDerivedData/\n")?;
    Ok(())
}
