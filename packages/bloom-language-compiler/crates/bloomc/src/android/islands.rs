//! Compose islands (ADR 0003): `.bloom` modules compiled to Kotlin + Jetpack Compose and
//! hosted inside the React Native app that `bloom build android` writes.
//!
//! A package marks a module `.module("FeedIsland", native: .island)`. The build then writes
//! the Gradle library `:bloom-islands` (`.bloom/build/native/bloom-islands`), which the app
//! links like Bloom's other native modules (autolinking, a `ReactPackage`):
//!
//! - the islands' Kotlin, from `bloom-native emit --target kotlin-compose --module <Island…>
//!   --std JSON,Core --runtime` (the native backend, `crates/native`): the modules, the
//!   standard library modules they use and Bloom's Kotlin runtime (`so.oxy.bloom.ui`,
//!   `so.oxy.bloom.std`, `BloomTheme.generated.kt`);
//! - `IslandRegistry`: each island by name, its module's `<Module>__island(props, emit)`
//!   (`FeedIsland` → `bloom.<app>.feedisland.FeedIsland__island`), which the backend writes:
//!   `props` is the JSON of the island's `Codable` props, `emit(name, payload)` an intent;
//! - `BloomIslandPackage`: the view `BloomIsland` (a Compose view), with the props `island`
//!   (which island) and `props` (JSON), and the direct event `onIslandEvent` (`{ name, payload }`).
//!   Its JS side is the standard library's `extern native "BloomIsland"` view.
//!
//! Compose comes in this library only: its compiler plugin, `runtime`, `ui` and `foundation`,
//! and coroutines. The app module stays React Native's.

use std::path::{Path, PathBuf};
use std::process::Command;

use super::autolink;
use crate::project::{Package, write};

/// The library's Gradle project and its dependency name (`:bloom-islands`).
pub const NAME: &str = "bloom-islands";
/// The Kotlin package of the registry and the view manager.
pub const PACKAGE: &str = "so.oxy.bloom.islands";
/// Compose, as the native backend's own Android project pins it.
pub const COMPOSE: &str = "1.12.1";
pub const COROUTINES: &str = "1.10.2";
/// The standard library modules an island may use, compiled through the backend.
pub const STD: &str = "JSON,Core";

/// The modules the package marks `native: .island`, in manifest order.
pub fn islands(package: &Package) -> Vec<String> {
    package.manifest.targets.iter().filter(|t| t.island).map(|t| t.name.clone()).collect()
}

/// The Kotlin package the native backend gives a module (`crates/native`'s `package_of`).
pub fn module_package(app: &str, module: &str) -> String {
    format!("bloom.{}.{}", app.to_lowercase(), module.to_lowercase())
}

/// The native backend: `$BLOOM_NATIVE`, else `bloom-native` beside this binary, else on the
/// `PATH`.
fn backend() -> PathBuf {
    if let Some(path) = std::env::var_os("BLOOM_NATIVE") {
        return PathBuf::from(path);
    }
    let beside = std::env::current_exe().ok().and_then(|exe| {
        exe.parent().map(|d| d.join(format!("bloom-native{}", std::env::consts::EXE_SUFFIX)))
    });
    beside.filter(|p| p.is_file()).unwrap_or_else(|| PathBuf::from("bloom-native"))
}

/// `IslandRegistry.kt`: each island's entry by name. An island module's entry is the
/// backend's `<Module>__island(props, emit)` in the module's package: `props` is the JSON of
/// the island's `Codable` props, and `emit(name, payload)` sends an intent (its payload JSON)
/// back to React Native.
pub fn registry(app: &str, islands: &[String]) -> String {
    let entries: String = islands
        .iter()
        .map(|name| {
            format!(
                "    \"{name}\" to @Composable {{ props: String, emit: (String, String) -> Unit -> {}.{name}__island(props, emit) }},\n",
                module_package(app, name)
            )
        })
        .collect();
    format!(
        r#"// Generated by bloom from Package.bloom (`native: .island` modules): regenerated on every build, never edited.
package {PACKAGE}

import androidx.compose.runtime.Composable

/** An island: drawn from its props (JSON), emitting its intents (a name and a JSON payload) back to React Native. */
typealias Island = @Composable (props: String, emit: (String, String) -> Unit) -> Unit

/** The Compose islands of this app, by module name. */
object IslandRegistry {{
  val islands: Map<String, Island> =
    mapOf(
{entries}    )
}}
"#
    )
}

/// `BloomIslandPackage.kt`: the view that hosts an island in the React Native tree.
pub fn package_source() -> String {
    format!(
        r#"// Generated by bloom: regenerated on every build, never edited.
package {PACKAGE}

import android.view.View
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import android.widget.FrameLayout
import androidx.compose.ui.platform.ComposeView
import androidx.compose.ui.platform.ViewCompositionStrategy
import com.facebook.react.ReactPackage
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.WritableMap
import com.facebook.react.uimanager.SimpleViewManager
import com.facebook.react.uimanager.ThemedReactContext
import com.facebook.react.uimanager.UIManagerHelper
import com.facebook.react.uimanager.ViewManager
import com.facebook.react.uimanager.annotations.ReactProp
import com.facebook.react.uimanager.events.Event
import androidx.compose.foundation.isSystemInDarkTheme
import so.oxy.bloom.ui.BloomThemeProvider
import so.oxy.bloom.ui.DEFAULT_PRESET

/** Registers the `BloomIsland` view (autolinked by `bloom build android`). */
class BloomIslandPackage : ReactPackage {{
  override fun createNativeModules(reactContext: ReactApplicationContext): List<NativeModule> = emptyList()

  override fun createViewManagers(reactContext: ReactApplicationContext): List<ViewManager<out View, *>> =
    listOf(BloomIslandViewManager())
}}

/**
 * An island in the React Native tree: the registry's `island`, drawn from `props` in Bloom's
 * theme. A change of `props` recomposes the island (its state is kept); a change of `island`
 * draws another. Each intent the island emits is an `onIslandEvent` with `{{ name, payload }}` (the
 * payload is JSON). Its content is set once ([Content]); a prop change only recomposes.
 */
class BloomIslandView(private val reactContext: ThemedReactContext) : FrameLayout(reactContext) {{
  var island by mutableStateOf<String?>(null)
  var props by mutableStateOf("{{}}")
  /** The app's theme: its colour preset (an `AppColorName`) and scheme (none: the system's). */
  var themePreset by mutableStateOf<String?>(null)
  var themeDark by mutableStateOf<Boolean?>(null)

  // Fabric may create and measure the view before it is attached (a screen mounted off-window,
  // preallocation), when Compose has no window recomposer: the island's ComposeView is added once
  // the view is attached, and drawn from then on.
  private val compose = ComposeView(reactContext).apply {{
    setViewCompositionStrategy(ViewCompositionStrategy.DisposeOnDetachedFromWindow)
    setContent {{ IslandContent() }}
  }}

  override fun onAttachedToWindow() {{
    super.onAttachedToWindow()
    if (compose.parent == null) addView(compose, LayoutParams(LayoutParams.MATCH_PARENT, LayoutParams.MATCH_PARENT))
    post(measureAndLayout)
  }}

  @Composable
  private fun IslandContent() {{
    val entry = island?.let {{ IslandRegistry.islands[it] }} ?: return
    val dark = themeDark ?: isSystemInDarkTheme()
    BloomThemeProvider(preset = themePreset ?: DEFAULT_PRESET, dark = dark) {{ entry(props, ::send) }}
  }}

  // React Native lays its views out itself and drops a child's `requestLayout`: the island's
  // content (set after attach, and on every size change it asks for) would never be measured.
  // The view measures and lays itself out at its current size instead, on the next frame.
  private val measureAndLayout = Runnable {{
    measure(
      MeasureSpec.makeMeasureSpec(width, MeasureSpec.EXACTLY),
      MeasureSpec.makeMeasureSpec(height, MeasureSpec.EXACTLY),
    )
    layout(left, top, right, bottom)
  }}

  override fun requestLayout() {{
    super.requestLayout()
    if (isAttachedToWindow) post(measureAndLayout)
  }}

  private fun send(name: String, payload: String) {{
    val dispatcher = UIManagerHelper.getEventDispatcherForReactTag(reactContext, id) ?: return
    val data =
      Arguments.createMap().apply {{
        putString("name", name)
        putString("payload", payload)
      }}
    dispatcher.dispatchEvent(IslandEvent(UIManagerHelper.getSurfaceId(this), id, data))
  }}

  private class IslandEvent(surfaceId: Int, viewId: Int, private val data: WritableMap) :
    Event<IslandEvent>(surfaceId, viewId) {{
    override fun getEventName(): String = EVENT

    override fun getEventData(): WritableMap = data
  }}

  companion object {{
    const val EVENT = "topIslandEvent"
  }}
}}

/** `BloomIsland`: its props are `island` (the registry's name) and `props` (JSON). */
class BloomIslandViewManager : SimpleViewManager<BloomIslandView>() {{
  override fun getName(): String = NAME

  override fun createViewInstance(context: ThemedReactContext): BloomIslandView = BloomIslandView(context)

  @ReactProp(name = "island")
  fun setIsland(view: BloomIslandView, island: String?) {{
    view.island = island
  }}

  @ReactProp(name = "props")
  fun setProps(view: BloomIslandView, props: String?) {{
    view.props = props ?: "{{}}"
  }}

  @ReactProp(name = "themePreset")
  fun setThemePreset(view: BloomIslandView, preset: String?) {{
    view.themePreset = preset
  }}

  /** `"dark"`, `"light"`, or none for the system's scheme. */
  @ReactProp(name = "themeScheme")
  fun setThemeScheme(view: BloomIslandView, scheme: String?) {{
    view.themeDark = when (scheme) {{ "dark" -> true; "light" -> false; else -> null }}
  }}

  override fun getExportedCustomDirectEventTypeConstants(): Map<String, Any> =
    mapOf(BloomIslandView.EVENT to mapOf("registrationName" to "onIslandEvent"))

  companion object {{
    const val NAME = "BloomIsland"
  }}
}}
"#
    )
}

/// The library's `build.gradle`: Kotlin, Compose and React Native, and its sources.
pub fn build_gradle(kotlin: &Path) -> String {
    format!(
        r#"// Generated by bloom: the Compose islands (`native: .island` modules), regenerated on every build.
apply plugin: "com.android.library"
apply plugin: "org.jetbrains.kotlin.android"
apply plugin: "org.jetbrains.kotlin.plugin.compose"

android {{
  namespace "{PACKAGE}"
  compileSdk rootProject.ext.compileSdkVersion
  defaultConfig {{
    minSdkVersion rootProject.ext.minSdkVersion
  }}
  buildFeatures {{
    compose true
  }}
  sourceSets {{
    main {{
      java.srcDirs += [{kotlin}]
    }}
  }}
}}

dependencies {{
  implementation("com.facebook.react:react-android")
  implementation("androidx.compose.runtime:runtime:{COMPOSE}")
  implementation("androidx.compose.ui:ui:{COMPOSE}")
  implementation("androidx.compose.foundation:foundation:{COMPOSE}")
  implementation("org.jetbrains.kotlinx:kotlinx-coroutines-android:{COROUTINES}")
}}
"#,
        kotlin = super::quote(&kotlin.to_string_lossy()),
    )
}

/// Writes `:bloom-islands` for the package's islands and returns it as a library to link, or
/// `None` when it marks none.
pub fn write_library(build: &Path, package: &Package) -> Result<Option<autolink::Library>, String> {
    let islands = islands(package);
    if islands.is_empty() {
        return Ok(None);
    }
    let root = build.join("native").join(NAME);
    let android = root.join("android");
    let kotlin = android.join("src/main/kotlin");
    // A clean tree each build: an island removed from the manifest leaves no Kotlin behind.
    let _ = std::fs::remove_dir_all(&kotlin);
    let bin = backend();
    let output = Command::new(&bin)
        .args([
            "emit",
            "--target",
            "kotlin-compose",
            "--module",
            &islands.join(","),
            "--std",
            STD,
            "--runtime",
        ])
        .arg(&package.root)
        .arg("--out")
        .arg(&kotlin)
        .output()
        .map_err(|e| {
            format!(
                "the native backend ({}) is needed for the islands {}: {e}; set BLOOM_NATIVE to it",
                bin.display(),
                islands.join(", ")
            )
        })?;
    if !output.status.success() {
        return Err(format!(
            "the native backend could not compile the islands {}:\n{}",
            islands.join(", "),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let generated = kotlin.join(PACKAGE.replace('.', "/"));
    write(&generated.join("IslandRegistry.kt"), &registry(&package.manifest.name, &islands))?;
    write(&generated.join("BloomIslandPackage.kt"), &package_source())?;
    write(&android.join("build.gradle"), &build_gradle(&kotlin))?;
    write(
        &android.join("src/main/AndroidManifest.xml"),
        "<manifest xmlns:android=\"http://schemas.android.com/apk/res/android\" />\n",
    )?;
    write(
        &root.join("package.json"),
        &format!("{{\n  \"name\": \"{NAME}\",\n  \"version\": \"1.0.0\",\n  \"private\": true\n}}\n"),
    )?;
    Ok(Some(autolink::Library {
        name: NAME.to_string(),
        root: root.clone(),
        source_dir: android.clone(),
        import: format!("import {PACKAGE}.BloomIslandPackage;"),
        instance: "new BloomIslandPackage()".into(),
        library_name: None,
        component_descriptors: Vec::new(),
        cmake_lists: android.join("build/generated/source/codegen/jni/CMakeLists.txt"),
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_registry_draws_each_island_by_its_module_s_entry() {
        let text = registry("Mention", &["FeedIsland".into(), "Settings".into()]);
        assert!(text.contains("package so.oxy.bloom.islands\n"), "{text}");
        assert!(
            text.contains(
                "    \"FeedIsland\" to @Composable { props: String, emit: (String, String) -> Unit -> bloom.mention.feedisland.FeedIsland__island(props, emit) },\n"
            ),
            "{text}"
        );
        assert!(text.contains("bloom.mention.settings.Settings__island(props, emit)"), "{text}");
        assert!(text.contains(
            "typealias Island = @Composable (props: String, emit: (String, String) -> Unit) -> Unit"
        ));
    }

    #[test]
    fn the_library_takes_compose_and_its_compiler_plugin() {
        let text = build_gradle(Path::new("/b/native/bloom-islands/android/src/main/kotlin"));
        for line in [
            "apply plugin: \"org.jetbrains.kotlin.plugin.compose\"",
            "compose true",
            "implementation(\"androidx.compose.runtime:runtime:1.12.1\")",
            "implementation(\"androidx.compose.ui:ui:1.12.1\")",
            "implementation(\"androidx.compose.foundation:foundation:1.12.1\")",
            "implementation(\"org.jetbrains.kotlinx:kotlinx-coroutines-android:1.10.2\")",
            "java.srcDirs += [\"/b/native/bloom-islands/android/src/main/kotlin\"]",
        ] {
            assert!(text.contains(line), "missing {line}:\n{text}");
        }
    }

    #[test]
    fn the_package_hosts_an_island_in_a_compose_view() {
        let text = package_source();
        assert!(text.contains("class BloomIslandPackage : ReactPackage"), "{text}");
        assert!(text.contains("const val NAME = \"BloomIsland\""), "{text}");
        assert!(text.contains("@ReactProp(name = \"island\")"), "{text}");
        // React Native drops a child's `requestLayout`: the island measures itself.
        assert!(text.contains("override fun requestLayout()"), "{text}");
        assert!(text.contains("@ReactProp(name = \"props\")"), "{text}");
        assert!(text.contains("\"registrationName\" to \"onIslandEvent\""), "{text}");
        assert!(text.contains("const val EVENT = \"topIslandEvent\""), "{text}");
        assert!(text.contains("entry(props, ::send)"), "{text}");
        assert!(
            text.contains("putString(\"name\", name)") && text.contains("putString(\"payload\", payload)"),
            "{text}"
        );
    }
}
