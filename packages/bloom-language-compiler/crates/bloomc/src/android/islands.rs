/// The library's Gradle project and its dependency name (`:bloom-islands`).
pub const NAME: &str = "bloom-islands";
/// The keyed islands' TurboModule (`BloomIslands.setProps(key, json)`), and its codegen library.
pub const MODULE: &str = "BloomIslands";
/// The Kotlin package of the registry and the view manager.
pub const PACKAGE: &str = "so.oxy.bloom.islands";
/// Compose, as the native backend's own Android project pins it.
pub const COMPOSE: &str = "1.12.1";
pub const COROUTINES: &str = "1.10.2";
/// The standard library modules an island may use, compiled through the backend.
pub const STD: &str = "JSON,Core";

/// The modules the package marks `native: .island`, in manifest order.
pub fn islands(package: &Package) -> Vec<String> {
    package.manifest.targets.iter().filter(|t| t.island).map(|t| t.name.clone()).collect()
}

/// The Kotlin package the native backend gives a module (`crates/native`'s `package_of`).
pub fn module_package(app: &str, module: &str) -> String {
    format!("bloom.{}.{}", app.to_lowercase(), module.to_lowercase())
}

/// The native backend: `$BLOOM_NATIVE`, else `bloom-native` beside this binary, else on the
/// `PATH`.
fn backend() -> PathBuf {
    if let Some(path) = std::env::var_os("BLOOM_NATIVE") {
        return PathBuf::from(path);
    }
    let beside = std::env::current_exe().ok().and_then(|exe| {
        exe.parent().map(|d| d.join(format!("bloom-native{}", std::env::consts::EXE_SUFFIX)))
    });
    beside.filter(|p| p.is_file()).unwrap_or_else(|| PathBuf::from("bloom-native"))
}

/// `IslandRegistry.kt`: each island's entry by name. An island module's entry is the
/// backend's `<Module>__island(props, emit)` in the module's package: `props` is the JSON of
/// the island's `Codable` props, and `emit(name, payload)` sends an intent (its payload JSON)
/// back to React Native.
pub fn registry(app: &str, islands: &[String]) -> String {
    let entries: String = islands
        .iter()
        .map(|name| {
            format!(
                "    \"{name}\" to @Composable {{ props: String, emit: (String, String) -> Unit -> {}.{name}__island(props, emit) }},\n",
                module_package(app, name)
            )
        })
        .collect();
    format!(
        r#"// Generated by bloom from Package.bloom (`native: .island` modules): regenerated on every build, never edited.
package {PACKAGE}

import androidx.compose.runtime.Composable

/** An island: drawn from its props (JSON), emitting its intents (a name and a JSON payload) back to React Native. */
typealias Island = @Composable (props: String, emit: (String, String) -> Unit) -> Unit

/** The Compose islands of this app, by module name. */
object IslandRegistry {{
  val islands: Map<String, Island> =
    mapOf(
{entries}    )
}}
"#
    )
}

