//! `bloom new <name> [--template app|module]`.

use std::path::Path;

use crate::expo::BLOOM_VERSION;
use crate::project::write;

/// Creates the package `name` in a new directory of that name.
pub fn new(name: &str, template: &str) -> Result<bool, String> {
    let valid = name.chars().next().is_some_and(|c| c.is_ascii_uppercase())
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if !valid {
        return Err(format!(
            "`{name}` is not a package name: it starts with a capital letter and has letters, digits and `_` (it is imported as written: `import {name}`)"
        ));
    }
    let root = Path::new(name);
    if root.exists() {
        return Err(format!("{name}/ already exists"));
    }
    let files = match template {
        "app" => app(name),
        "module" => module(name),
        other => return Err(format!("no template `{other}`: use `--template app` or `--template module`")),
    };
    for (path, text) in &files {
        write(&root.join(path), text)?;
    }
    println!("created {name}/ ({template}):");
    for (path, _) in &files {
        println!("  {path}");
    }
    if template == "app" {
        println!("\nnext:\n  cd {name}\n  bloom run web");
    }
    Ok(true)
}

const GITIGNORE: &str = "# Generated by bloom: the build directory, caches and module interfaces.\n.bloom/\n";

fn app(name: &str) -> Vec<(String, String)> {
    let kit = format!("{name}Kit");
    vec![
        (
            "Package.bloom".into(),
            format!(
                r#"let package = Package(
  name: "{name}",
  platforms: [.iOS(17), .android(26), .web],
  dependencies: [
    .package("Bloom", from: "{BLOOM_VERSION}"),
  ],
  targets: [
    .app("{name}", dependencies: ["{kit}"]),
    .module("{kit}"),
    .tests("{kit}Tests", dependencies: ["{kit}"]),
  ]
)
"#
            ),
        ),
        (
            format!("Sources/{name}/App.bloom"),
            format!(
                r#"import Bloom
import {kit}

/// The app's root view: `bloom build` starts here.
public view App {{
  body {{
    VStack {{
      Text(greeting(name: "{name}"))
    }}
    .padding("lg")
  }}
}}
"#
            ),
        ),
        (
            format!("Sources/{kit}/Greeting.bloom"),
            r#"/// The greeting the app shows.
public func greeting(name: String) -> String {
  "Hello, \(name)!"
}
"#
            .into(),
        ),
        (
            format!("Tests/{kit}Tests/GreetingTests.bloom"),
            format!(
                r#"import {kit}

test("greets by name") {{
  #expect(greeting(name: "Ada") == "Hello, Ada!")
}}
"#
            ),
        ),
        (".gitignore".into(), GITIGNORE.into()),
    ]
}

fn module(name: &str) -> Vec<(String, String)> {
    vec![
        (
            "Package.bloom".into(),
            format!(
                r#"let package = Package(
  name: "{name}",
  dependencies: [
    .package("Bloom", from: "{BLOOM_VERSION}"),
  ],
  targets: [
    .module("{name}"),
    .tests("{name}Tests", dependencies: ["{name}"]),
  ]
)
"#
            ),
        ),
        (
            format!("Sources/{name}/{name}.bloom"),
            format!(
                r#"/// What `{name}` offers the modules that import it.
public func describe() -> String {{
  "{name}"
}}
"#
            ),
        ),
        (
            format!("Tests/{name}Tests/{name}Tests.bloom"),
            format!(
                r#"import {name}

test("describes itself") {{
  #expect(describe() == "{name}")
}}
"#
            ),
        ),
        (".gitignore".into(), GITIGNORE.into()),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn templates_have_a_valid_manifest() {
        for files in [app("Demo"), module("Strings")] {
            let manifest = &files[0].1;
            let parsed = bloom_lang::package::parse(manifest, "Package.bloom");
            assert!(parsed.is_ok(), "{:?}", parsed.err());
            let parsed = parsed.unwrap();
            for target in &parsed.targets {
                let dir = target.dir().to_string_lossy().into_owned();
                assert!(files.iter().any(|(p, _)| p.starts_with(&dir)), "{dir} has no file");
            }
        }
    }
}
