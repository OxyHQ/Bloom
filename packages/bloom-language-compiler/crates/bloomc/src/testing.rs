//! `bloom test`: the package's `.tests` targets, run by Jest underneath.
//!
//! A test file is a `.bloom` file of a `.tests` target (`test("name") { … }`,
//! `#expect(…)`); the compiler lowers it onto a small runtime (`bloom:testing`,
//! written to `.bloom/build/testing.js`), and Jest runs the compiled files
//! through the compiler's Jest adapter.

use crate::expo::{generate, run_in};
use crate::project::{CheckOptions, Package, check_modules};

/// The runtime `test` and `#expect` lower onto.
pub const RUNTIME: &str = r#"// Generated by bloom: the runtime of `test("…") { … }` and `#expect(…)`.
const util = require('node:util');

exports.test = (name, body) => globalThis.test(name, body);

exports.expect = (condition, source) => {
  if (!condition) throw new Error(`#expect(${source}) failed`);
};

exports.expectEqual = (actual, expected, source) => {
  if (!util.isDeepStrictEqual(actual, expected)) {
    throw new Error(`#expect(${source}) failed: ${util.inspect(actual)} is not ${util.inspect(expected)}`);
  }
};
"#;

/// Jest's config in `.bloom/build/`: the package's `Tests/` compiled by the Bloom adapter.
pub const JEST_CONFIG: &str = r#"// Generated by bloom from Package.bloom: regenerated on every build, never edited.
const path = require('node:path');

module.exports = {
  rootDir: path.resolve(__dirname, '../..'),
  roots: ['<rootDir>/Tests'],
  testMatch: ['**/*.bloom'],
  moduleFileExtensions: ['bloom', 'ts', 'tsx', 'js', 'json'],
  transform: {
    '\\.(bloom|[jt]sx?)$': [
      require.resolve('@oxy.so/bloom-language-compiler/jest'),
      { upstream: [require.resolve('babel-jest'), { configFile: path.join(__dirname, 'babel.config.js') }] },
    ],
  },
  moduleNameMapper: { '^bloom:testing$': path.join(__dirname, 'testing.js') },
  modulePaths: [path.join(__dirname, 'node_modules')],
  transformIgnorePatterns: ['/node_modules/(?!(@oxy\\.so|react-native|@react-native|expo|@expo)/)'],
  testEnvironment: 'node',
};
"#;

/// Checks the package, then runs its tests (those whose name contains `filter`).
pub fn run(package: &Package, filter: Option<String>, options: &CheckOptions) -> Result<bool, String> {
    if package.targets_of(|k| matches!(k, bloom_lang::package::TargetKind::Tests)).is_empty() {
        println!("bloom: no `.tests` target in Package.bloom");
        return Ok(true);
    }
    if !check_modules(package, options, false)?.ok {
        return Ok(false);
    }
    generate(package)?;
    crate::deps::install(package)?;
    let workers = format!("--maxWorkers={}", options.jobs.clamp(1, 3));
    let mut args = vec!["x", "jest", "--config", "jest.config.js", workers.as_str()];
    if let Some(filter) = &filter {
        args.extend(["-t", filter.as_str()]);
    }
    match run_in(&package.build_dir(), "bun", &args) {
        Ok(()) => Ok(true),
        Err(_) => Ok(false),
    }
}
