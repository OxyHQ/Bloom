#!/usr/bin/env node
// Writes crates/lang/src/swift_tokens.generated.rs: each token set of
// packages/bloom-language/spec/language.json with its tokens' Swift names, so
// `.padding(.md)`, `.spacing(.xxl)` and `.font(.caption1)` compile to the token
// strings ("md", "2xl", "caption-1"). For the native iOS backend (ADR 0003) it also
// writes, from the same spec, the Swift backend's node table
// (crates/native/src/swift/nodes.generated.rs: each constructor's own modifiers, the
// constructors that take children) and BloomUI's tokens
// (crates/native/runtime/ios/Sources/BloomUI/Generated/Tokens.generated.swift: each token
// set as a Swift enum, the scales' values, the type ramp). Never edit the outputs by hand;
// run `node scripts/generate-swift-tokens.mjs` (or with `--check` to verify them).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokenSetsOf } from '../../bloom-language/scripts/token-sets.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = join(root, '../bloom-language/spec/language.json');
const outPath = join(root, 'crates/lang/src/swift_tokens.generated.rs');
const nodesPath = join(root, 'crates/native/src/swift/nodes.generated.rs');
const swiftTokensPath = join(
  root,
  'crates/native/runtime/ios/Sources/BloomUI/Generated/Tokens.generated.swift',
);
const check = process.argv.includes('--check');

/** `2xl` → `xxl`, `caption-1` → `caption1`, `top-leading` → `topLeading`; `null` for a token
 * with no Swift name (a number, a CSS value). */
export function swiftName(token) {
  let name = token.replace(/^(\d)x([ls])\b/, (_, n, end) => 'x'.repeat(Number(n)) + end);
  name = name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return /^[a-z][A-Za-z0-9]*$/.test(name) ? name : null;
}

/** SwiftUI's names for a set's tokens, where they differ: `HStack(alignment: .top)` aligns
 * the children's starts (cross-axis), as `.leading` does in a `VStack`. */
const ALIASES = {
  alignment: {
    top: 'start',
    leading: 'start',
    bottom: 'end',
    trailing: 'end',
    firstTextBaseline: 'baseline',
  },
};

const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const sets = tokenSetsOf(spec);
const lines = [];
for (const [set, tokens] of Object.entries(sets).sort(([a], [b]) => a.localeCompare(b))) {
  const pairs = [];
  const seen = new Set();
  for (const token of tokens) {
    const swift = swiftName(token);
    if (swift === null || seen.has(swift)) continue;
    seen.add(swift);
    pairs.push(`(${JSON.stringify(swift)}, ${JSON.stringify(token)})`);
  }
  for (const [swift, token] of Object.entries(ALIASES[set] ?? {})) {
    if (tokens.includes(token) && !seen.has(swift)) {
      seen.add(swift);
      pairs.push(`(${JSON.stringify(swift)}, ${JSON.stringify(token)})`);
    }
  }
  if (pairs.length > 0) lines.push(`    (${JSON.stringify(set)}, &[${pairs.join(', ')}]),`);
}

const text = `//! Generated by scripts/generate-swift-tokens.mjs from spec/language.json. Do not edit.
//!
//! Each token set's Swift names (\`.xxl\`) and the tokens they compile to (\`"2xl"\`).

/// Token set name → (Swift name, token), in the set's order.
pub const SWIFT_TOKENS: &[(&str, &[(&str, &str)])] = &[
${lines.join('\n')}
];
`;

// ---- the native Swift backend's node table -------------------------------------------

const universal = spec.universal;
const ownModifiers = [];
const children = new Set();
for (const [kind, node] of Object.entries(spec.nodes)) {
  if (kind === '$comment') continue;
  for (const constructor of node.constructors ?? []) {
    const own = (node.modifiers ?? []).filter((m) => node.universal === false || !universal.includes(m));
    ownModifiers.push([constructor, own]);
    const signature = spec.signatures[constructor] ?? [];
    if (signature.includes('...children')) children.add(constructor);
  }
}
ownModifiers.sort(([a], [b]) => a.localeCompare(b));
const rustList = (items) => `&[${items.map((m) => JSON.stringify(m)).join(', ')}]`;
const nodesText = `//! Generated by scripts/generate-swift-tokens.mjs from spec/language.json. Do not edit.
//!
//! What the Swift backend needs of BloomUI's nodes: each constructor's own modifiers (its
//! methods in BloomUI, written on the node before the universal ones), and the
//! constructors whose trailing closure is a view builder.

/// Constructor → its own modifiers (beyond the universal ones), sorted by constructor.
pub const OWN_MODIFIERS: &[(&str, &[&str])] = &[
${ownModifiers.map(([c, own]) => `    (${JSON.stringify(c)}, ${rustList(own)}),`).join('\n')}
];

/// The constructors that take children (\`VStack { … }\`).
pub const CHILDREN: &[&str] = ${rustList([...children].sort())};

/// The modifiers every node takes.
pub const UNIVERSAL: &[&str] = ${rustList(universal)};
`;

// ---- BloomUI's tokens, as Swift --------------------------------------------------------

const SWIFT_KEYWORDS = new Set([
  'default', 'in', 'is', 'as', 'self', 'Self', 'init', 'Type', 'case', 'class', 'func', 'let',
  'var', 'if', 'else', 'for', 'while', 'return', 'switch', 'where', 'do', 'repeat', 'true',
  'false', 'nil', 'import', 'static', 'struct', 'enum', 'protocol', 'extension', 'public',
  'private', 'internal', 'operator', 'throw', 'throws', 'try', 'catch', 'break', 'continue',
  'defer', 'guard', 'inout', 'super', 'subscript', 'typealias', 'associatedtype', 'fallthrough',
]);
const swiftCase = (name) => (SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name);
const typeName = (set) => set[0].toUpperCase() + set.slice(1);
const scaleTables = Object.fromEntries(
  Object.entries(spec.scales).map(([name, table]) => [
    name,
    Object.fromEntries(Object.entries(table).filter(([k]) => k !== '$comment')),
  ]),
);
const swiftEnums = [];
for (const [set, tokens] of Object.entries(sets).sort(([a], [b]) => a.localeCompare(b))) {
  const cases = [];
  const seen = new Set();
  for (const token of tokens) {
    const name = swiftName(token);
    if (name === null || seen.has(name)) continue;
    seen.add(name);
    cases.push([name, token]);
  }
  for (const [name, token] of Object.entries(ALIASES[set] ?? {})) {
    if (tokens.includes(token) && !seen.has(name)) {
      seen.add(name);
      cases.push([name, token, true]);
    }
  }
  if (cases.length === 0) continue;
  const primary = cases.filter(([, , alias]) => !alias);
  const aliases = cases.filter(([, , alias]) => alias);
  const lines = primary.map(([name, token]) => `    case ${swiftCase(name)} = ${JSON.stringify(token)}`);
  for (const [name, token] of aliases) {
    const target = primary.find(([, t]) => t === token)?.[0];
    if (target) lines.push(`    public static let ${swiftCase(name)}: ${typeName(set)} = .${swiftCase(target)}`);
  }
  const scale = scaleTables[set];
  const numeric = scale && primary.some(([, token]) => typeof scale[token] === 'number');
  let values = '';
  if (numeric) {
    const arms = primary
      .filter(([, token]) => typeof scale[token] === 'number')
      .map(([name, token]) => `      case .${swiftCase(name)}: ${Number(scale[token])}`);
    const total = arms.length === primary.length;
    values = `

    /// The token's value in points (the spec's \`scales.${set}\`)${total ? '' : '; \`nil\` for a token with no fixed value'}.
    public var value: Double${total ? '' : '?'} {
      switch self {
${arms.join('\n')}${total ? '' : '\n      default: nil'}
      }
    }`;
  }
  swiftEnums.push(`  /// \`${set}\`: ${primary.length} token(s).
  public enum ${typeName(set)}: String, Sendable, CaseIterable {
${lines.join('\n')}${values}
  }`);
}
const ramp = Object.entries(spec.typeRamp).filter(([k]) => k !== '$comment');
const rampLines = ramp.map(
  ([name, [size, line, tracking, weight]]) =>
    `    ${JSON.stringify(name)}: TypeStyle(size: ${size}, lineHeight: ${line}, tracking: ${tracking}, weight: ${Number(weight)}),`,
);
const swiftTokensText = `// Generated by packages/bloom-language-compiler/scripts/generate-swift-tokens.mjs from
// packages/bloom-language/spec/language.json. Do not edit.
//
// BloomUI's tokens on Swift: each token set of the language as an enum whose raw value is
// the token (\`Tokens.Space.xxl.rawValue == "2xl"\`), the scales' values in points, and the
// type ramp. The colours are the theme's (BloomTheme), never here.

public enum Tokens {
${swiftEnums.join('\n\n')}

  /// A step of the type ramp: \`[fontSize, lineHeight, letterSpacing, fontWeight]\`.
  public struct TypeStyle: Sendable, Equatable {
    public let size: Double
    public let lineHeight: Double
    public let tracking: Double
    public let weight: Int
  }

  /// The type ramp, by \`<family>-<weight>\` (\`body-regular\`, \`headline-semibold\`).
  public static let typeRamp: [String: TypeStyle] = [
${rampLines.join('\n')}
  ]
}
`;

const outputs = [
  [outPath, text],
  [nodesPath, nodesText],
  [swiftTokensPath, swiftTokensText],
];
if (check) {
  let stale = false;
  for (const [path, expected] of outputs) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {}
    if (current !== expected) {
      console.error(`stale: ${path} (run: node scripts/generate-swift-tokens.mjs)`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('swift token names are current');
} else {
  for (const [path, expected] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, expected);
  }
  console.log(`wrote ${outPath} (${lines.length} sets), ${nodesPath}, ${swiftTokensPath}`);
}
