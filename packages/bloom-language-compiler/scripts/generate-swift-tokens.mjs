#!/usr/bin/env node
// Writes crates/lang/src/swift_tokens.generated.rs: each token set of
// packages/bloom-language/spec/language.json with its tokens' Swift names, so
// `.padding(.md)`, `.spacing(.xxl)` and `.font(.caption1)` compile to the token
// strings ("md", "2xl", "caption-1"). Never edit the output by hand; run
// `node scripts/generate-swift-tokens.mjs` (or with `--check` to verify it).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokenSetsOf } from '../../bloom-language/scripts/token-sets.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = join(root, '../bloom-language/spec/language.json');
const outPath = join(root, 'crates/lang/src/swift_tokens.generated.rs');
const check = process.argv.includes('--check');

/** `2xl` → `xxl`, `caption-1` → `caption1`, `top-leading` → `topLeading`; `null` for a token
 * with no Swift name (a number, a CSS value). */
export function swiftName(token) {
  let name = token.replace(/^(\d)x([ls])\b/, (_, n, end) => 'x'.repeat(Number(n)) + end);
  name = name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return /^[a-z][A-Za-z0-9]*$/.test(name) ? name : null;
}

/** SwiftUI's names for a set's tokens, where they differ: `HStack(alignment: .top)` aligns
 * the children's starts (cross-axis), as `.leading` does in a `VStack`. */
const ALIASES = {
  alignment: { top: 'start', leading: 'start', bottom: 'end', trailing: 'end', firstTextBaseline: 'baseline' },
};

const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const sets = tokenSetsOf(spec);
const lines = [];
for (const [set, tokens] of Object.entries(sets).sort(([a], [b]) => a.localeCompare(b))) {
  const pairs = [];
  const seen = new Set();
  for (const token of tokens) {
    const swift = swiftName(token);
    if (swift === null || seen.has(swift)) continue;
    seen.add(swift);
    pairs.push(`(${JSON.stringify(swift)}, ${JSON.stringify(token)})`);
  }
  for (const [swift, token] of Object.entries(ALIASES[set] ?? {})) {
    if (tokens.includes(token) && !seen.has(swift)) {
      seen.add(swift);
      pairs.push(`(${JSON.stringify(swift)}, ${JSON.stringify(token)})`);
    }
  }
  if (pairs.length > 0) lines.push(`    (${JSON.stringify(set)}, &[${pairs.join(', ')}]),`);
}

const text = `//! Generated by scripts/generate-swift-tokens.mjs from spec/language.json. Do not edit.
//!
//! Each token set's Swift names (\`.xxl\`) and the tokens they compile to (\`"2xl"\`).

/// Token set name → (Swift name, token), in the set's order.
pub const SWIFT_TOKENS: &[(&str, &[(&str, &str)])] = &[
${lines.join('\n')}
];
`;

if (check) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {}
  if (current !== text) {
    console.error(`stale: ${outPath} (run: node scripts/generate-swift-tokens.mjs)`);
    process.exit(1);
  }
  console.log('swift token names are current');
} else {
  writeFileSync(outPath, text);
  console.log(`wrote ${outPath} (${lines.length} sets)`);
}
