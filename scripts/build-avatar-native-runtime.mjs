/** Compile the shared engine for Hermes. Assets stay external and retain the same
 * transport hashes as the browser build; the factory accepts the hosting base. */
import { build } from 'vite';
import { resolve } from 'node:path';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { avatarMotionTransport } from './avatar-motion-transport.mjs';
import { avatarSurfaceTransport } from './avatar-surface-transport.mjs';
const output = resolve('.local/avatar-native-runtime-build');
const webOutput = resolve('.local/avatar-native-compatible-web');
// Compile the browser entry from the SAME checkout first: shaders and controller
// changes must invalidate compatibility even if binary asset names do not change.
if (process.env.AVATAR_NATIVE_SOURCE_ROOT)
  throw Error('Build native and browser entries from the same checkout');
execFileSync(process.execPath, ['scripts/build-avatar-runtime.mjs'], {
  env: { ...process.env, AVATAR_RUNTIME_OUTPUT: webOutput },
  stdio: 'inherit',
});
const entry = resolve('runtime/avatar-native-entry.ts');
await build({
  configFile: false,
  publicDir: false,
  base: './',
  plugins: [
    {
      name: 'native-avatar-asset-base',
      resolveFileUrl({ fileName }) {
        return `resolveNativeAvatarAsset(${JSON.stringify(fileName)})`;
      },
    },
    avatarSurfaceTransport(),
    avatarMotionTransport(),
  ],
  experimental: {
    renderBuiltUrl(filename) {
      return { runtime: `resolveNativeAvatarAsset(${JSON.stringify(filename)})` };
    },
  },
  build: {
    outDir: output,
    emptyOutDir: true,
    target: 'es2020',
    assetsInlineLimit: 0,
    modulePreload: false,
    rollupOptions: {
      input: entry,
      preserveEntrySignatures: 'strict',
      output: {
        format: 'iife',
        name: 'BloomNativeAvatarEngine',
        inlineDynamicImports: true,
        entryFileNames: 'runtime.js',
        assetFileNames: 'assets/[name]-[hash][extname]',
      },
    },
  },
});
const code = await readFile(resolve(output, 'runtime.js'), 'utf8');
if (/import\.meta|document\.currentScript|data:application\/octet-stream|eval\(/.test(code))
  throw Error('Native runtime must not require module URLs, embedded binary assets or eval');
const wrapped = `/** Generated by scripts/build-avatar-native-runtime.mjs. */\nmodule.exports = function createNativeAvatarRuntime(assetBaseURL) {\nconst resolveNativeAvatarAsset = filename => new URL(filename, assetBaseURL).href;\n${code}\nreturn BloomNativeAvatarEngine;\n};\n`;
const destination = resolve('packages/avatar-native/lib');
await mkdir(destination, { recursive: true });
await writeFile(resolve(destination, 'runtime.cjs'), wrapped);
const files = {};
async function inventory(directory, prefix = '') {
  for (const item of await readdir(directory, { withFileTypes: true })) {
    const name = prefix + item.name;
    const path = resolve(directory, item.name);
    if (item.isDirectory()) await inventory(path, name + '/');
    else
      files[name] = createHash('sha256')
        .update(await readFile(path))
        .digest('hex');
  }
}
await inventory(webOutput);
for (const filename of await readdir(resolve(output, 'assets'))) {
  const hash = createHash('sha256')
    .update(await readFile(resolve(output, 'assets', filename)))
    .digest('hex');
  if (files[`assets/${filename}`] !== hash)
    throw Error(`Native/browser asset mismatch: ${filename}`);
}
const manifest = JSON.stringify({ version: 1, entry: 'runtime.mjs', files }, null, 2) + '\n';
await writeFile(resolve(destination, 'asset-manifest.json'), manifest);
await writeFile(resolve(webOutput, 'manifest.json'), manifest);
console.log(`Native engine: ${Buffer.byteLength(wrapped)} bytes; external assets in ${output}`);
