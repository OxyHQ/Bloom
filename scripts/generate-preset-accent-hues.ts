/**
 * Generate `src/theme/preset-accent-hues.ts`: the split-complementary accent
 * hues of every built-in preset seed, precomputed.
 *
 * `deriveAccentHues` (color-policy.ts) searches ~50 hues of 63 HCT solves each,
 * which was most of a theme's cold solve on device. Presets are a fixed
 * registry, so their answers are checked in; any other seed still solves at
 * runtime. `preset-accent-hues.test.ts` asserts this table equals the search for
 * every preset, so a preset or policy change that forgets to re-run this fails.
 *
 *   bun run generate:preset-accent-hues
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { argbFromHex } from '../src/theme/color-engine';
import { Hct } from '../src/theme/color-engine/hct';
import { deriveAccentHues } from '../src/theme/color-policy';
import { COLOR_PRESET_REGISTRY } from '../src/theme/color-presets';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repoRoot, 'src', 'theme', 'preset-accent-hues.ts');

const seeds = [...new Set(COLOR_PRESET_REGISTRY.map((preset) => preset.hex.toLowerCase()))];
const rows = seeds.map((hex) => {
  const { secondary, tertiary } = deriveAccentHues(Hct.fromInt(argbFromHex(hex)).hue);
  // `String(number)` is the shortest round-tripping form, so the table parses
  // back to the identical doubles.
  return `  '${hex}': { secondary: ${secondary}, tertiary: ${tertiary} },`;
});

const source = `/**
 * AUTO-GENERATED by scripts/generate-preset-accent-hues.ts — DO NOT EDIT.
 * Re-run \`bun run generate:preset-accent-hues\` after changing a preset seed or
 * the accent search in color-policy.ts; preset-accent-hues.test.ts fails until then.
 *
 * Each built-in preset seed's \`deriveAccentHues\`, keyed by lowercase seed hex.
 */
import type { AccentHues } from './color-policy';

export const PRESET_ACCENT_HUES: Readonly<Record<string, AccentHues>> = {
${rows.join('\n')}
};
`;

writeFileSync(outputPath, source);
console.log(
  `[generate-preset-accent-hues] wrote ${relative(repoRoot, outputPath)} (${seeds.length} seeds)`,
);
