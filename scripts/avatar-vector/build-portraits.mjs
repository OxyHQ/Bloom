/** Run with Bun: imports the same pure TypeScript projector used by both clients. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = fileURLToPath(new URL('../..', import.meta.url));
const assetRoot = path.join(root, 'src/agent-avatar/vector-assets');
const modulePath =
  process.env.BLOOM_VECTOR_FRAME_MODULE || path.join(root, 'src/agent-avatar/vector-frame.ts');
const { renderVectorFrame } = await import(pathToFileURL(modulePath).href);
const manifest = JSON.parse(await fs.readFile(path.join(assetRoot, 'manifest.json'), 'utf8'));
const sharedGeometry = new Map();
for (const group of manifest.sharedGeometry ?? []) {
  const packed = JSON.parse(await fs.readFile(path.join(assetRoot, group.file), 'utf8'));
  for (const [key, geometry] of Object.entries(JSON.parse(packed.data)))
    sharedGeometry.set(key, geometry);
}
const read = async (file) => {
  const packed = JSON.parse(await fs.readFile(path.join(assetRoot, file), 'utf8'));
  const data = packed.encoding === 'json' ? JSON.parse(packed.data) : packed;
  for (const part of data.parts ?? [])
    if (part.geometryRef) Object.assign(part, sharedGeometry.get(part.geometryRef));
  return data;
};
const shapeFrames = {},
  eyeFrames = {};
for (const entry of manifest.files) {
  if (entry.kind !== 'shape' && entry.kind !== 'eyes') continue;
  const data = await read(entry.file);
  if (entry.kind === 'shape') {
    const indices = data.parts
      .map((part, i) => (part.role === 'body' ? i : -1))
      .filter((i) => i >= 0);
    const selected = {
      ...data,
      parts: indices.map((i) => data.parts[i]),
      clips: Object.fromEntries(
        Object.entries(data.clips).map(([name, clip]) => [
          name,
          { ...clip, parts: indices.map((i) => clip.parts[i]) },
        ]),
      ),
    };
    shapeFrames[entry.id] = renderVectorFrame(selected, { action: 'idle', time: 0 });
  } else eyeFrames[entry.id] = renderVectorFrame(data, { action: 'idle', time: 0, eyesOnly: true });
}
eyeFrames.bot = renderVectorFrame(await read('shape-bot_blob.json'), {
  action: 'idle',
  time: 0,
  eyesOnly: true,
});
const text = [
  '// Generated by scripts/build-avatar-vector-assets.mjs. Do not edit by hand.',
  "import type { VectorFrame } from './vector-types';",
  `export const vectorShapePortraits: Readonly<Record<string, VectorFrame>> = ${JSON.stringify(shapeFrames)};`,
  `export const vectorEyePortraits: Readonly<Record<string, VectorFrame>> = ${JSON.stringify(eyeFrames)};`,
  '',
].join('\n');
await fs.writeFile(path.join(root, 'src/agent-avatar/vector-static.ts'), text);
console.log(
  'Static vector portraits:',
  Object.keys(shapeFrames).length,
  'bodies,',
  Object.keys(eyeFrames).length,
  'faces,',
  Buffer.byteLength(text),
  'bytes',
);
