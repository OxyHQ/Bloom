// @ts-check
/**
 * Generate `src/fonts/font-data.web.ts` — base64 data URLs for the Bloom
 * web font assets.
 *
 * Why this exists:
 *   The web build (`apply-font-faces.web.ts`) needs URLs to plug into
 *   `@font-face { src: url(...) }`. The obvious approach — module-level
 *   `import x from './assets/X.woff2'` — only works when the consuming
 *   bundler has an asset loader configured for `.woff2`.
 *
 *   Metro (the bundler Expo uses for both native AND web) does NOT include
 *   `.woff2` in its default `assetExts`. Every downstream app would have to
 *   hand-edit its `metro.config.js`, which is exactly the kind of papercut
 *   a UI library must not push onto consumers.
 *
 *   Inlining as base64 data URLs sidesteps the bundler entirely: the
 *   published JS contains the font bytes as string literals, so any
 *   bundler that can parse JavaScript can ship Bloom's fonts. Total cost
 *   is ~310 KB of base64 added to the web bundle — comparable to what
 *   Material UI, Mantine, and other major UI libraries do for their
 *   bundled fonts. `font-display: swap` keeps FOUT short.
 *
 * Output:
 *   - `src/fonts/font-data.web.ts` (generated, gitignored)
 *
 * Wired as a `prebuild` step so `bun run build` always regenerates the
 * file before bob compiles. Local dev (`bun run test`, `bun run typescript`)
 * also calls this via the same `prebuild` hook through `bun run build`
 * — for ad-hoc runs use `bun run generate:font-data` directly.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..');
const FONTS_DIR = join(REPO_ROOT, 'src', 'fonts');
const ASSETS_DIR = join(FONTS_DIR, 'assets');
const OUTPUT_PATH = join(FONTS_DIR, 'font-data.web.ts');

/**
 * @typedef {Object} FontEntry
 * @property {string} exportName  Identifier exported from the generated module.
 * @property {string} filename    Filename under `src/fonts/assets/`.
 */

/** @type {readonly FontEntry[]} */
const FONTS = [
  { exportName: 'blomusModernusRegular', filename: 'BlomusModernus-Regular.woff2' },
  { exportName: 'blomusModernusBold', filename: 'BlomusModernus-Bold.woff2' },
  { exportName: 'interVariable', filename: 'InterVariable.woff2' },
  { exportName: 'geistMonoVariable', filename: 'GeistMono-Variable.woff2' },
];

function toDataUrl(filePath) {
  const bytes = readFileSync(filePath);
  return `data:font/woff2;base64,${bytes.toString('base64')}`;
}

function buildSource() {
  const header = [
    '// AUTO-GENERATED by scripts/generate-font-data.mjs — DO NOT EDIT.',
    '//',
    '// Base64 data URLs for the Bloom web font set. Inlined so consuming',
    '// apps do not need a bundler asset rule for `.woff2`. Regenerated on',
    '// every `bun run build` via the `prebuild` hook.',
    '//',
    '// Each constant is explicitly typed as `string` (not the inferred',
    '// string literal) so the emitted `.d.ts` stays tiny — otherwise TS',
    '// would preserve the full base64 payload in the declaration file,',
    '// bloating install size for downstream consumers.',
    '',
    '',
  ].join('\n');

  const entries = FONTS.map(({ exportName, filename }) => {
    const dataUrl = toDataUrl(join(ASSETS_DIR, filename));
    return `export const ${exportName}: string = ${JSON.stringify(dataUrl)};`;
  }).join('\n');

  return `${header}${entries}\n`;
}

function main() {
  const source = buildSource();
  writeFileSync(OUTPUT_PATH, source);

  const sizeKb = Math.round(source.length / 1024);
  console.log(
    `[generate-font-data] wrote ${OUTPUT_PATH} (${sizeKb} KB, ${FONTS.length} fonts)`,
  );
}

main();
