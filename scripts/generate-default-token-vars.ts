/**
 * Generate `src/theme/default-token-vars.ts`: Bloom's default palette (the
 * `oxy` preset, light), precomputed as each canonical token's value.
 *
 * `useColorTokens()` answers this palette on native outside any provider. Read
 * from a table, that answer does not import the colour engine, so a component
 * that paints through the tokens (every `Text`) keeps the engine out of a
 * bundle that has no provider of its own (`verify-avatar-bundle-size.mjs`).
 * `default-token-vars.test.ts` asserts the table equals
 * `buildScopeVars('oxy', 'light')`, so a preset or policy change that forgets
 * to re-run this fails.
 *
 *   bun run generate:default-token-vars
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CANONICAL_TOKENS } from '../src/theme/canonical-tokens';
import { buildScopeVars } from '../src/theme/color-scope/style-builder';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repoRoot, 'src', 'theme', 'default-token-vars.ts');

const vars = buildScopeVars('oxy', 'light');
const rows = CANONICAL_TOKENS.map((name) => {
  const value = vars[`--${name}`];
  if (value === undefined) throw new Error(`buildScopeVars('oxy', 'light') has no --${name}`);
  return `  '--${name}': '${value}',`;
});

const source = `/**
 * AUTO-GENERATED by scripts/generate-default-token-vars.ts — DO NOT EDIT.
 * Re-run \`bun run generate:default-token-vars\` after changing the oxy preset or
 * the colour policy; default-token-vars.test.ts fails until then.
 *
 * Bloom's default palette (\`oxy\`, light): every canonical token's value, as
 * \`buildScopeVars('oxy', 'light')\` resolves it.
 */
import type { CanonicalToken } from './canonical-tokens';

export const DEFAULT_TOKEN_VARS: Readonly<Record<\`--\${CanonicalToken}\`, string>> = {
${rows.join('\n')}
};
`;

writeFileSync(outputPath, source);
console.log(
  `[generate-default-token-vars] wrote ${relative(repoRoot, outputPath)} (${rows.length} tokens)`,
);
