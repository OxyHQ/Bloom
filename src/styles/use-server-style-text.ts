import { useMemo, useState, useSyncExternalStore } from 'react';
import { Platform } from 'react-native';

const subscribe = () => () => {};
const clientSnapshot = () => true;
const serverSnapshot = () => false;

/**
 * Expensive server sheets can be adopted verbatim during hydration. Their
 * deterministic variable references do not require recomputing every server
 * variant in the browser. The live factory runs only for a client render, after
 * hydration has published the actual theme; ServerStyleSheet owns adoption and
 * removal of the matching server node as usual.
 */
export function useServerStyleText(
  id: string,
  server: () => string,
  client: () => string,
  liveReady = true,
  reuseServer = true,
): string {
  const ready = useSyncExternalStore(subscribe, clientSnapshot, serverSnapshot);
  const [initial] = useState(() => {
    if (!reuseServer || Platform.OS !== 'web' || typeof document === 'undefined') return undefined;
    // IDs are generated by Bloom's useId owners. Compare the attribute rather
    // than interpolating it into a selector, so this helper accepts any ID.
    const node = Array.from(document.querySelectorAll('[data-bloom-server-style]')).find(
      (element) => element.getAttribute('data-bloom-server-style') === id,
    );
    return node?.textContent ?? undefined;
  });
  return useMemo(
    () => (ready && liveReady ? client() : (initial ?? server())),
    [ready, liveReady, initial, server, client],
  );
}
